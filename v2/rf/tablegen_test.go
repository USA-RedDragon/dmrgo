func renderTables() ([]byte, error) {
	tabs, err := derivedTables()
	if err != nil {
		return nil, err
	}
	imports := map[string]bool{}
	for _, tab := range tabs {
		typeImports(reflect.TypeOf(tab.v), imports)
	}
	var b strings.Builder
	b.WriteString("// Code generated by TestTablesGenerated in tablegen_test.go. DO NOT EDIT.\n\npackage rf\n")
	for _, p := range slices.Sorted(maps.Keys(imports)) {
		fmt.Fprintf(&b, "\nimport %q\n", p)
	}
	for _, tab := range tabs {
		fmt.Fprintf(&b, "\nvar %s = ", tab.name)
		if err := renderValue(&b, reflect.ValueOf(tab.v), true); err != nil {
			return nil, fmt.Errorf("%s: %w", tab.name, err)
		}
		b.WriteString("\n")
	}
	return format.Source([]byte(b.String()))
}

func renderValue(b *strings.Builder, v reflect.Value, typed bool) error {
	switch v.Kind() {
	case reflect.Struct:
		if typed {
			b.WriteString(typeName(v.Type()))
		}
		b.WriteString("{\n")
		for i := range v.NumField() {
			f := v.Field(i)
			if f.IsZero() {
				continue
			}
			fmt.Fprintf(b, "%s: ", v.Type().Field(i).Name)
			if err := renderValue(b, f, true); err != nil {
				return err
			}
			b.WriteString(",\n")
		}
		b.WriteString("}")
	case reflect.Array:
		if typed {
			b.WriteString(typeName(v.Type()))
		}
		n := v.Len()
		for n > 0 && v.Index(n-1).IsZero() {
			n--
		}
		k := v.Type().Elem().Kind()
		nested := k == reflect.Struct || k == reflect.Array
		b.WriteString("{")
		for i := range n {
			switch {
			case nested:
				b.WriteString("\n")
			case i > 0:
				b.WriteString(", ")
			}
			if err := renderValue(b, v.Index(i), false); err != nil {
				return err
			}
			if nested {
				b.WriteString(",")
			}
		}
		if nested && n > 0 {
			b.WriteString("\n")
		}
		b.WriteString("}")
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		b.WriteString(strconv.FormatInt(v.Int(), 10))
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		b.WriteString(strconv.FormatUint(v.Uint(), 10))
	case reflect.Bool:
		b.WriteString(strconv.FormatBool(v.Bool()))
	case reflect.Float32, reflect.Float64:
		s, err := renderFloat(v.Float(), v.Type().Bits())
		if err != nil {
			return err
		}
		b.WriteString(s)
	case reflect.Complex64, reflect.Complex128:
		bits := v.Type().Bits() / 2
		re, err := renderFloat(real(v.Complex()), bits)
		if err != nil {
			return err
		}
		im, err := renderFloat(imag(v.Complex()), bits)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "complex(%s, %s)", re, im)
	default:
		return fmt.Errorf("cannot render a %s", v.Type())
	}
	return nil
}

func renderFloat(x float64, bits int) (string, error) {
	if math.IsNaN(x) || math.IsInf(x, 0) || x == 0 && math.Signbit(x) {
		return "", fmt.Errorf("%v has no constant", x)
	}
	return strconv.FormatFloat(x, 'g', -1, bits), nil
}

const rfPath = "github.com/USA-RedDragon/dmrgo/v2/rf"

func typeImports(t reflect.Type, set map[string]bool) {
	if p := t.PkgPath(); p != "" && p != rfPath {
		set[p] = true
	}
	switch t.Kind() {
	case reflect.Array:
		typeImports(t.Elem(), set)
	case reflect.Struct:
		for i := range t.NumField() {
			typeImports(t.Field(i).Type, set)
		}
	default:
	}
}

func typeName(t reflect.Type) string {
	if t.Name() != "" && t.PkgPath() != rfPath {
		return t.String()
	}
	if t.Name() != "" {
		return t.Name()
	}
	if t.Kind() == reflect.Array {
		return "[" + strconv.Itoa(t.Len()) + "]" + typeName(t.Elem())
	}
	return t.String()
}
