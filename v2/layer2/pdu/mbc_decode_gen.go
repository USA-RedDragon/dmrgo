// EncodeBits returns the bits that Encode returns as a slice, or nil and
// the error of Encode.
func (s *VNAPContinuation) EncodeBits() ([]bit.Bit, error) {
	bits, err := s.Encode()
	if err != nil {
		return nil, err
	}
	return bits[:], nil
}

