var updateTables = flag.Bool("update", false, "rewrite tables_gen.go from the table derivations")

const tablesFile = "tables_gen.go"

func tier0Pulses() []struct {
	name  string
	hz    int
	p     pulse
	units float64
} {
	t := []struct {
		name  string
		hz    int
		p     pulse
		units float64
	}{
		{"taps24k", 24000, pulse{span: 8}, tableUnits},
		{"taps48k", 48000, pulse{span: 6}, tableUnits},
		{"tapsIQ", 24000, pulse{span: 4}, tableUnits},
	}
	if !tier0Exact {
		return t
	}
	for i := range t {
		t[i].p.nyquist()
		hz := float64(t[i].hz)
		if t[i].name == "tapsIQ" {
			t[i].p.invert(hz, interpChain(hz, math.Inf(1)))
		} else {
			t[i].p.invert(hz, holdChain(hz))
		}
	}
	return t
}

// roundSum rounds the values of v to integers whose sum is the rounded
// sum of v, by the largest remainders.
func roundSum(v []float64) []int {
	out := make([]int, len(v))
	var sum float64
	got := 0
	for i, x := range v {
		out[i] = int(math.Floor(x))
		got += out[i]
		sum += x
	}
	for want := int(math.Round(sum)); got < want; got++ {
		best := -1
		for i, x := range v {
			if out[i] == int(math.Floor(x)) && (best < 0 || x-math.Floor(x) > v[best]-math.Floor(v[best])) {
				best = i
			}
		}
		out[best]++
	}
	return out
}

func TestTablesGenerated(t *testing.T) {
	t.Parallel()
	src, err := renderTables()
	if err != nil {
		t.Fatal(err)
	}
	if *updateTables {
		if err := os.WriteFile(tablesFile, src, 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(tablesFile)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, src) {
		t.Errorf("%s is out of date; run go generate ./... in the root module", tablesFile)
	}
}

// renderLUT writes tapsIQLUT: for each pair of symbols, newer and older,
// at taps 2j and 2j+1 of tapsIQ, each index 5 times the code of the newer
// symbol plus the code of the older, and each pair of phases 2g and 2g+1,
// the sum over those two taps, phase 2g in the low half of the word and
// phase 2g+1 in the high half. The codes 0 to 4 are the symbols -3, -1,
// +1, +3 and 0; the indexes 25 to 31 are zero, so that a mask of 5 bits
// indexes the table. Each sum over all taps is under 3*tapsIQPeak, within
// int16, so that the halves of the word sum stay apart.
func renderLUT(b *bytes.Buffer, h []float64, l, n int) {
	tap := func(p, i int) int32 {
		if p >= l {
			return 0
		}
		return int32(int16(math.Round(h[p*n+i] * tableUnits / 3)))
	}
	val := [5]int32{-3, -1, 1, 3, 0}
	fmt.Fprintf(b, "var tapsIQLUT = [%d][32][%d]int32{\n", n/2, (l+1)/2)
	for j := range n / 2 {
		b.WriteString("{")
		for q := range 32 {
			b.WriteString("{")
			for g := range (l + 1) / 2 {
				var v int32
				if q < 25 {
					for k, c := range [2]int{q / 5, q % 5} {
						v += (tap(2*g, 2*j+k) + tap(2*g+1, 2*j+k)<<16) * val[c]
					}
				}
				fmt.Fprintf(b, "%d,", v)
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
}

func renderTables() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by TestTablesGenerated in tablegen_test.go. DO NOT EDIT.\n\npackage fsktx\n\n")
	for _, t := range tier0Pulses() {
		l := t.hz / SymbolRate
		h := t.p.taps(l, 1)
		n := 2 * t.p.span
		peak := 0
		fmt.Fprintf(&b, "var %s = [%d][%d]int16{\n", t.name, l, n)
		for p := range l {
			b.WriteString("{")
			sum := 0
			row := make([]int, n)
			for i := range n {
				row[i] = int(int16(math.Round(h[p*n+i] * t.units / 3)))
			}
			if tier0Exact {
				// Each phase passes a run of one symbol at exactly units.
				x := make([]float64, n)
				var s float64
				for i := range n {
					x[i] = h[p*n+i] * t.units / 3
					s += x[i]
				}
				for i := range n {
					x[i] += (t.units/3 - s) / float64(n)
				}
				row = roundSum(x)
			}
			for _, v := range row {
				sum += max(v, -v)
				fmt.Fprintf(&b, "%d,", v)
			}
			peak = max(peak, sum)
			b.WriteString("},\n")
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "const %sPeak = %d\n\n", t.name, peak)
		if t.name == "tapsIQ" {
			renderLUT(&b, h, l, n)
		}
	}
	renderCorr(&b)
	if err := renderCorrIQ(&b); err != nil {
		return nil, err
	}
	fmt.Fprintf(&b, "var cosTable = [%d]int16{", 1<<cosTableBits+cosQuarter+1)
	for i := range 1<<cosTableBits + cosQuarter + 1 {
		fmt.Fprintf(&b, "%d,", int16(math.Round(iqAmplitude*math.Cos(2*math.Pi*float64(i)/(1<<cosTableBits)))))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// corrIQFile holds the correction of tier0IQCorr in Hz, fitted from the
// phase optimizer of Tier2: C symbols of context ending K symbols before
// the newest, for a pulse of 16 symbols on each side, at 48 kHz.
const corrIQFile = "testdata/mcorriq-c4.json"

// renderCorrIQ writes corrIQ and its context, each two phases in a word
// as tapsIQLUT, or an empty table when
// tier0IQCorr is off. It needs tapsIQ at 48 kHz.
func renderCorrIQ(b *bytes.Buffer) error {
	var span, l int
	for _, t := range tier0Pulses() {
		if t.name == "tapsIQ" {
			span, l = t.p.span, t.hz/SymbolRate
		}
	}
	if !tier0IQCorr {
		fmt.Fprintf(b, "const (\ncorrIQSyms = 1\ncorrIQSkip = 0\n)\n\nvar corrIQ [4][%d]int32\n\n", (l+1)/2)
		return nil
	}
	raw, err := os.ReadFile(corrIQFile)
	if err != nil {
		return err
	}
	var c struct {
		C, K int
		Hz   []float64
	}
	if err := json.Unmarshal(raw, &c); err != nil {
		return err
	}
	skip := c.K - 16 + span
	if l != 10 || skip < 0 || len(c.Hz) != 10<<(2*c.C) {
		return fmt.Errorf("%s: bad context or rate", corrIQFile)
	}
	fmt.Fprintf(b, "const (\ncorrIQSyms = %d\ncorrIQSkip = %d\n)\n\n", c.C, skip)
	fmt.Fprintf(b, "var corrIQ = [%d][5]int32{\n", 1<<(2*c.C))
	for i := range 1 << (2 * c.C) {
		b.WriteString("{")
		for g := range 5 {
			lo := int32(int16(math.Round(c.Hz[i*10+2*g] * tableUnits / 1944)))
			hi := int32(int16(math.Round(c.Hz[i*10+2*g+1] * tableUnits / 1944)))
			fmt.Fprintf(b, "%d,", lo+hi<<16)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
	return nil
}
