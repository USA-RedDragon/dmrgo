const tablesFile = "tables_gen.go"

func tier0Pulses() []struct {
	name  string
	hz    int
	p     pulse
	units float64
} {
	t := []struct {
		name  string
		hz    int
		p     pulse
		units float64
	}{
		{"taps24k", 24000, pulse{span: 8, win: winBlackman}, tableUnits},
		{"taps48k", 48000, pulse{span: 6, win: winBlackman}, tableUnits},
		{"tapsIQ", 48000, pulse{span: 8, win: winKaiser, beta: 3, ridge: 1e-5}, tableUnits},
	}
	if !tier0Exact {
		return t
	}
	for i := range t {
		t[i].p.nyquist()
		hz := float64(t[i].hz)
		if t[i].name == "tapsIQ" {
			t[i].p.invert(hz, interpChain(hz, math.Inf(1)))
		} else {
			t[i].p.invert(hz, holdChain(hz))
		}
	}
	return t
}

func roundSum(v []float64) []int {
	out := make([]int, len(v))
	var sum float64
	got := 0
	for i, x := range v {
		out[i] = int(math.Floor(x))
		got += out[i]
		sum += x
	}
	for want := int(math.Round(sum)); got < want; got++ {
		best := -1
		for i, x := range v {
			if out[i] == int(math.Floor(x)) && (best < 0 || x-math.Floor(x) > v[best]-math.Floor(v[best])) {
				best = i
			}
		}
		out[best]++
	}
	return out
}

func TestTablesGenerated(t *testing.T) {
	t.Parallel()
	if testmode.Race && !*updateTables && !corrFitsCached() {
		t.Skip("the fit of the audio corrections is not in the user cache and takes an hour under -race; the runs without -race and go generate check it")
	}
	src, err := renderTables()
	if err != nil {
		t.Fatal(err)
	}
	if *updateTables {
		if err := os.WriteFile(tablesFile, src, 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(tablesFile)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, src) {
		t.Errorf("%s is out of date; run go generate ./... in the root module", tablesFile)
	}
}

func renderLUT(b *bytes.Buffer, h []float64, l, n int) {
	tap := func(p, i int) int32 {
		if p >= l {
			return 0
		}
		return int32(int16(math.Round(h[p*n+i] * tableUnits / 3)))
	}
	val := [5]int32{-3, -1, 1, 3, 0}
	fmt.Fprintf(b, "var tapsIQLUT = [%d][32][%d]int32{\n", n/2, (l+1)/2)
	for j := range n / 2 {
		b.WriteString("{")
		for q := range 32 {
			b.WriteString("{")
			for g := range (l + 1) / 2 {
				var v int32
				if q < 25 {
					for k, c := range [2]int{q / 5, q % 5} {
						v += (tap(2*g, 2*j+k) + tap(2*g+1, 2*j+k)<<16) * val[c]
					}
				}
				fmt.Fprintf(b, "%d,", v)
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
}

func renderFold(b *bytes.Buffer, rows [][]int) error {
	ok := len(rows) == 10 && len(rows[0]) == 12 && rows[0][0] == 0
	for p := 1; ok && p < 10; p++ {
		for i := range 12 {
			ok = ok && rows[p][i] == rows[10-p][11-i]
		}
	}
	for i := 1; ok && i < 12; i++ {
		ok = rows[0][i] == rows[0][12-i]
	}
	if !ok && tier0Fold {
		return fmt.Errorf("taps48k is not symmetric, so tier0Fold cannot fold it")
	}
	var f [5][12]int
	if ok {
		for k := range 4 {
			for i := range 6 {
				f[k][i] = rows[k+1][i] + rows[k+1][11-i]
				f[k][6+i] = rows[k+1][i] - rows[k+1][11-i]
			}
		}
		copy(f[4][:6], rows[5][:6])
		copy(f[4][6:], rows[0][1:7])
	}
	b.WriteString("var taps48kFold = [5][12]int16{\n")
	for _, r := range f {
		b.WriteString("{")
		for _, v := range r {
			if v != int(int16(v)) {
				return fmt.Errorf("taps48kFold: %d does not fit int16", v)
			}
			fmt.Fprintf(b, "%d,", v)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
	return nil
}

func renderFold24(b *bytes.Buffer, rows [][]int) error {
	ok := len(rows) == 5 && len(rows[0]) == 16
	for p := 1; ok && p < 5; p++ {
		for i := range 16 {
			ok = ok && rows[p][i] == rows[5-p][15-i]
		}
	}
	if !ok && tier0Fold {
		return fmt.Errorf("taps24k is not symmetric, so tier0Fold cannot fold it")
	}
	var f [3][16]int
	if ok {
		copy(f[0][:], rows[0])
		for k := range 2 {
			for i := range 8 {
				f[k+1][i] = rows[k+1][i] + rows[k+1][15-i]
				f[k+1][8+i] = rows[k+1][i] - rows[k+1][15-i]
			}
		}
	}
	b.WriteString("var taps24kFold = [3][16]int16{\n")
	for _, r := range f {
		b.WriteString("{")
		for _, v := range r {
			if v != int(int16(v)) {
				return fmt.Errorf("taps24kFold: %d does not fit int16", v)
			}
			fmt.Fprintf(b, "%d,", v)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
	return nil
}

func renderTables() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by TestTablesGenerated in tablegen_test.go. DO NOT EDIT.\n\npackage fsktx\n\n")
	for _, t := range tier0Pulses() {
		if t.name != "tapsIQ" {
			t.units *= 1 << tapShift
		}
		l := t.hz / SymbolRate
		h := t.p.taps(l, 1)
		n := 2 * t.p.span
		peak := 0
		fmt.Fprintf(&b, "var %s = [%d][%d]int16{\n", t.name, l, n)
		rows := make([][]int, l)
		for p := range l {
			b.WriteString("{")
			sum := 0
			row := make([]int, n)
			for i := range n {
				row[i] = int(int16(math.Round(h[p*n+i] * t.units / 3)))
			}
			if tier0Exact {
				x := make([]float64, n)
				var s float64
				for i := range n {
					x[i] = h[p*n+i] * t.units / 3
					s += x[i]
				}
				for i := range n {
					x[i] += (t.units/3 - s) / float64(n)
				}
				row = roundSum(x)
			}
			for _, v := range row {
				sum += max(v, -v)
				fmt.Fprintf(&b, "%d,", v)
			}
			rows[p] = row
			peak = max(peak, sum)
			b.WriteString("},\n")
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "const %sPeak = %d\n\n", t.name, peak)
		if t.name == "taps24k" {
			if err := renderFold24(&b, rows); err != nil {
				return nil, err
			}
		}
		if t.name == "taps48k" {
			if err := renderFold(&b, rows); err != nil {
				return nil, err
			}
		}
		if t.name == "tapsIQ" {
			renderLUT(&b, h, l, n)
		}
	}
	renderAudioCorr(&b)
	if err := renderMCUCorr(&b, mcuCorrFile, "mcuCorr"); err != nil {
		return nil, err
	}
	renderPreEmph(&b)
	renderNyquist(&b)
	if err := renderMCUCorr(&b, mcuCorrPEFile, "mcuCorrPE"); err != nil {
		return nil, err
	}
	if err := renderCorrIQ(&b); err != nil {
		return nil, err
	}
	if tier0IQWide {
		fmt.Fprintf(&b, "var cosTable = [%d]int32{", 1<<cosTableBits+cosQuarter+1)
		for i := range 1<<cosTableBits + cosQuarter + 1 {
			v := math.Round(iqAmplitude*65536*math.Cos(2*math.Pi*(float64(i-cosQuarter)+0.5)/(1<<cosTableBits))) + 32768
			fmt.Fprintf(&b, "%d,", int32(v))
		}
	} else {
		fmt.Fprintf(&b, "var cosTable = [%d]int16{", 1<<cosTableBits+cosQuarter+1)
		for i := range 1<<cosTableBits + cosQuarter + 1 {
			fmt.Fprintf(&b, "%d,", int16(math.Round(iqAmplitude*math.Cos(2*math.Pi*float64(i)/(1<<cosTableBits)))))
		}
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

const corrIQFile = "testdata/mcorriq-o51e.json"

func renderCorrIQ(b *bytes.Buffer) error {
	var span, l int
	for _, t := range tier0Pulses() {
		if t.name == "tapsIQ" {
			span, l = t.p.span, t.hz/SymbolRate
		}
	}
	if !tier0IQCorr {
		fmt.Fprintf(b, "const (\ncorrIQSyms = 1\ncorrIQSkip = 0\ncorrIQLen = 1\ncorrIQSym = false\n)\n\nvar corrIQ [1][4][%d]int32\n\n", (l+1)/2)
		return nil
	}
	raw, err := os.ReadFile(corrIQFile)
	if err != nil {
		return err
	}
	var c struct {
		C, K, L int
		Sym     bool
		Hz      []float64
	}
	if err := json.Unmarshal(raw, &c); err != nil {
		return err
	}
	c.L = max(c.L, 1)
	rows := 1 << (2 * c.C)
	if c.Sym {
		rows /= 2
	}
	skip := c.K - 16 + span
	if l != 10 || skip-c.L+1 < 0 || skip+c.C > 16 || len(c.Hz) != 10*rows*c.L {
		return fmt.Errorf("%s: bad context or rate", corrIQFile)
	}
	fmt.Fprintf(b, "const (\ncorrIQSyms = %d\ncorrIQSkip = %d\ncorrIQLen = %d\ncorrIQSym = %v\n)\n\n", c.C, skip, c.L, c.Sym)
	fmt.Fprintf(b, "var corrIQ = [%d][%d][5]int32{\n", c.L, rows)
	for k := range c.L {
		b.WriteString("{\n")
		for i := range rows {
			b.WriteString("{")
			for g := range 5 {
				o := (k*rows+i)*10 + 2*g
				lo := int32(int16(math.Round(c.Hz[o] * tableUnits / 1944)))
				hi := int32(int16(math.Round(c.Hz[o+1] * tableUnits / 1944)))
				fmt.Fprintf(b, "%d,", lo+hi<<16)
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
	return nil
}

const (
	mcuCorrFile   = "testdata/mcorr48k-c5r2.json"
	mcuCorrPEFile = "testdata/mcorr48k-pe.json"
)

func renderMCUCorr(b *bytes.Buffer, file, name string) error {
	if !tier0Corr {
		if name != "mcuCorr" {
			fmt.Fprintf(b, "const (\n%sSkip = 0\n%sPeak = 0\n)\n\nvar %s [4][10]int16\n\n", name, name, name)
			return nil
		}
		b.WriteString("const (\nmcuCorrSyms = 1\nmcuCorrSkip = 0\nmcuCorrBase = 4\nmcuCorrTop = 1\nmcuCorrPeak = 0\n)\n\nvar mcuCorr [4][10]int16\n\n")
		return nil
	}
	raw, err := os.ReadFile(file)
	if err != nil {
		return err
	}
	var c struct {
		C, K, Base int
		Hz         []float64
	}
	if err := json.Unmarshal(raw, &c); err != nil {
		return err
	}
	if c.Base == 0 {
		c.Base = 4
	}
	rows := 1
	for range c.C {
		rows *= c.Base
	}
	top := rows / c.Base
	skip := c.K - 8 + 6
	if skip < 0 || len(c.Hz) != 10*rows || c.Base != 4 && c.Base != 5 {
		return fmt.Errorf("%s: bad context", file)
	}
	u := tableUnits * (1 << tapShift) / 1944.0
	peak := 0
	for _, v := range c.Hz {
		peak = max(peak, int(math.Abs(float64(int16(math.Round(v*u))))))
	}
	if name == "mcuCorr" {
		fmt.Fprintf(b, "const (\nmcuCorrSyms = %d\nmcuCorrSkip = %d\nmcuCorrBase = %d\nmcuCorrTop = %d\nmcuCorrPeak = %d\n)\n\n", c.C, skip, c.Base, top, peak)
	} else {
		if c.C != 5 || c.Base != 4 {
			return fmt.Errorf("%s: the context must match mcuCorr", file)
		}
		fmt.Fprintf(b, "const (\n%sSkip = %d\n%sPeak = %d\n)\n\n", name, skip, name, peak)
	}
	fmt.Fprintf(b, "var %s = [%d][10]int16{\n", name, rows)
	for i := range rows {
		b.WriteString("{")
		for p := range 10 {
			fmt.Fprintf(b, "%d,", int16(math.Round(c.Hz[i*10+p]*u)))
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
	return nil
}

func renderNyquist(b *bytes.Buffer) {
	fmt.Fprintf(b, "var tierShapeTab = [%d]float64{", len(tierShapeSrc))
	for _, v := range tierShapeSrc {
		fmt.Fprintf(b, "%v,", v)
	}
	b.WriteString("}\n\n")
	ps := tierPulses()
	ps[1].tab = tierShapeSrc
	fmt.Fprintf(b, "var nyquistEcho = [%d][%d]float64{\n", len(ps), 4*maxTaps+1)
	for _, p := range ps {
		p.solveNyquist()
		b.WriteString("{")
		for _, v := range p.echo {
			fmt.Fprintf(b, "%v,", v)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
}

