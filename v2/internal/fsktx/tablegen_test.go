package fsktx

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"math"
	"os"
	"testing"
)

var updateTables = flag.Bool("update", false, "rewrite tables_gen.go from the table derivations")

const tablesFile = "tables_gen.go"

func tier0Pulses() []struct {
	name string
	hz   int
	p    pulse
} {
	return []struct {
		name string
		hz   int
		p    pulse
	}{
		{"taps24k", 24000, pulse{span: 8}},
		{"taps48k", 48000, pulse{span: 6}},
		{"tapsIQ", 24000, pulse{span: 4}},
	}
}

func TestTablesGenerated(t *testing.T) {
	t.Parallel()
	src, err := renderTables()
	if err != nil {
		t.Fatal(err)
	}
	if *updateTables {
		if err := os.WriteFile(tablesFile, src, 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(tablesFile)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, src) {
		t.Errorf("%s is out of date; run go generate ./... in the root module", tablesFile)
	}
}

// renderPairs writes tapsIQPairs: the taps of phases 2g and 2g+1 of
// tapsIQ in one word, low and high half, for two multiply and accumulates
// in one. Each sum is under 3*tapsIQPeak, within int16, so that the halves
// of the word sum stay apart.
func renderPairs(b *bytes.Buffer, h []float64, l, n int) {
	tap := func(p, i int) int32 {
		if p >= l {
			return 0
		}
		return int32(int16(math.Round(h[p*n+i] * tableUnits / 3)))
	}
	fmt.Fprintf(b, "var tapsIQPairs = [%d][%d]int32{\n", (l+1)/2, n)
	for g := range (l + 1) / 2 {
		b.WriteString("{")
		for i := range n {
			fmt.Fprintf(b, "%d,", tap(2*g, i)+tap(2*g+1, i)<<16)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
}

func renderTables() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by TestTablesGenerated in tablegen_test.go. DO NOT EDIT.\n\npackage fsktx\n\n")
	for _, t := range tier0Pulses() {
		l := t.hz / SymbolRate
		h := t.p.taps(l, 1)
		n := 2 * t.p.span
		peak := 0
		fmt.Fprintf(&b, "var %s = [%d][%d]int16{\n", t.name, l, n)
		for p := range l {
			b.WriteString("{")
			sum := 0
			for i := range n {
				v := int16(math.Round(h[p*n+i] * tableUnits / 3))
				sum += max(int(v), -int(v))
				fmt.Fprintf(&b, "%d,", v)
			}
			peak = max(peak, sum)
			b.WriteString("},\n")
		}
		b.WriteString("}\n\n")
		fmt.Fprintf(&b, "const %sPeak = %d\n\n", t.name, peak)
		if t.name == "tapsIQ" {
			renderPairs(&b, h, l, n)
		}
	}
	fmt.Fprintf(&b, "var cosTable = [%d]int16{", 1<<cosTableBits+1)
	for i := range 1<<cosTableBits + 1 {
		fmt.Fprintf(&b, "%d,", int16(math.Round(iqAmplitude*math.Cos(2*math.Pi*float64(i)/(1<<cosTableBits)))))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
