// Sizes of the fit of the correction tables.
const (
	corrFitSyms = 240000
	corrFitOpt  = 30
	corrFitSkip = 200
)

// corrFit is one correction table: its rate, context symbols and skip,
// and its corrections in Hz.
type corrFit struct {
	hz, syms, skip int
	t              []float64
}

// fitCorr runs Opt at corrFitOpt iterations over corrFitSyms random
// symbols at hz and fits, for each context length in syms, the mean
// correction per context of the symbols that ends 3 to 7 symbols before
// the newest, with the skip that explains the most of its power.
func fitCorr(hz int, syms []int) []corrFit {
	cfg := AudioConfig{Hz: hz, Tier: Tier1, Exact: true, Pulse: corrPulse()}
	a0, err := NewAudio(cfg)
	if err != nil {
		panic(err)
	}
	cfg.Opt = corrFitOpt
	a1, err := NewAudio(cfg)
	if err != nil {
		panic(err)
	}
	spp := hz / SymbolRate
	rng := rand.New(rand.NewPCG(3, 4))
	sy := make([]int8, corrFitSyms)
	y0 := make([]float64, 0, corrFitSyms*spp)
	y1 := make([]float64, 0, corrFitSyms*spp)
	buf := make([]float64, len(a0.buf))
	for i := range sy {
		s := int8(rng.IntN(4)*2 - 3)
		sy[i] = s
		n := a0.k.symbol(buf, s)
		y0 = append(y0, buf[:n]...)
		n = a1.k.symbol(buf, s)
		a1.opt.process(buf[:n])
		y1 = append(y1, buf[:n]...)
	}
	d := a1.opt.delay
	c := make([]float64, len(y0)-d)
	var tot float64
	for i := range c {
		c[i] = y1[i+d] - y0[i]
		if i >= corrFitSkip*spp {
			tot += c[i] * c[i]
		}
	}
	var out []corrFit
	for _, C := range syms {
		best := corrFit{hz: hz, syms: C}
		bestEx := 0.0
		for K := 3; K <= 7; K++ {
			idxOf := func(j int) int {
				idx := 0
				for i := j - K - C + 1; i <= j-K; i++ {
					idx = idx<<2 | int(sy[i]+3)/2
				}
				return idx
			}
			sum := make([]float64, spp<<(2*C))
			cnt := make([]float64, 1<<(2*C))
			end := len(c)/spp - 1
			for j := corrFitSkip; j < end; j++ {
				idx := idxOf(j)
				cnt[idx]++
				for p := range spp {
					sum[idx*spp+p] += c[j*spp+p]
				}
			}
			for i := range sum {
				if cnt[i/spp] > 0 {
					sum[i] /= cnt[i/spp]
				}
			}
			var res float64
			for j := corrFitSkip; j < end; j++ {
				idx := idxOf(j)
				for p := range spp {
					e := c[j*spp+p] - sum[idx*spp+p]
					res += e * e
				}
			}
			if ex := 1 - res/tot; ex > bestEx {
				bestEx, best.skip, best.t = ex, K, sum
			}
		}
		out = append(out, best)
	}
	return out
}

// renderAudioCorr writes the correction tables of AudioConfig.Corr: for each
// rate and context length, the corrections at corrUnits per Hz and the
// skip of the context.
func renderAudioCorr(b *bytes.Buffer) {
	rates := []int{24000, 48000}
	fits := make([][]corrFit, len(rates))
	var wg sync.WaitGroup
	for i, hz := range rates {
		wg.Add(1)
		go func() {
			defer wg.Done()
			fits[i] = fitCorr(hz, []int{5, 6})
		}()
	}
	wg.Wait()
	for _, fs := range fits {
		for _, f := range fs {
			name := fmt.Sprintf("corr%dk%d", f.hz/1000, f.syms)
			fmt.Fprintf(b, "const %sSkip = %d\n\n", name, f.skip)
			fmt.Fprintf(b, "var %s = [%d]int16{", name, len(f.t))
			for i, v := range f.t {
				if i%20 == 0 {
					b.WriteString("\n")
				}
				fmt.Fprintf(b, "%d,", int16(max(-32767, min(32767, math.Round(v*corrUnits)))))
			}
			b.WriteString("\n}\n\n")
		}
	}
}
