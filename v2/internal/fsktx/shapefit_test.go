var updateKern = flag.Bool("updatekern", false, "rewrite shapekern_gen.go from a fit to the optimizer")

// Settings of the fit of the predictor kernels.
const (
	fitSymbols = 30000
	fitIters   = 30
	fitRidge   = 1e-6
	fitLo      = 80
	fitTaps    = 160
	fitGaps    = true
	fitTopHz   = 16000.0
	fitTopN    = 41
	// fitACPB is the ACP weight of the optimizer of shapeKernB.
	fitACPB = 42.0
)

// fitLowPass is a Kaiser low pass at hz of n taps with unit gain at 0 Hz,
// at iqShaperHz.
func fitLowPass(hz float64, n int) []float64 {
	if hz <= 0 {
		return []float64{1}
	}
	h := make([]float64, n)
	fc := hz / iqShaperHz
	var sum float64
	for i := range h {
		t := float64(i - n/2)
		v := 2 * fc
		if t != 0 {
			v = math.Sin(2*math.Pi*fc*t) / (math.Pi * t)
		}
		x := t / float64(n/2+1)
		h[i] = v * besselI0(8*math.Sqrt(max(0, 1-x*x))) / besselI0(8)
		sum += h[i]
	}
	for i := range h {
		h[i] /= sum
	}
	return h
}

// TestShapeKernFit fits the predictor kernels to the corrections of the
// optimizer on random symbols, and with -updatekern writes them.
func TestShapeKernFit(t *testing.T) {
	if !*updateKern {
		t.Skip("only with -updatekern")
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by TestShapeKernFit -updatekern; DO NOT EDIT.\n\npackage fsktx\n\n")
	out := fitKern(t, Tier2, predPulse, nil, 0, false)
	writeKern(&b, "shapeKern", "the kernels of the predictor, by sample, then by product of symbols", out)
	outB := fitKern(t, Tier2, predPulse, out, fitACPB, true)
	writeKern(&b, "shapeKernB", "the kernels of PredKern 1, as shapeKern", outB)
	src, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile("shapekern_gen.go", src, 0o644); err != nil {
		t.Fatal(err)
	}
}

// writeKern writes the kernels k as the variable name.
func writeKern(b *bytes.Buffer, name, doc string, k *[predK][predF]float64) {
	fmt.Fprintf(b, "// %s are %s.\n", name, doc)
	fmt.Fprintf(b, "var %s = [predK][predF]float64{\n", name)
	for i := range predK {
		b.WriteString("{")
		for _, v := range k[i] {
			fmt.Fprintf(b, "%.6g, ", v)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
}

// fitKern fits the kernels of the tier and pulse to the correction of
// the optimizer with the ACP weight acp, its blocks unchained with
// noChain; with warm, to the sum of the correction of the predictor with
// the kernels warm and of the optimizer that starts from it.
func fitKern(t *testing.T, tier Tier, pc PulseConfig, warm *[predK][predF]float64, acp float64, noChain bool) *[predK][predF]float64 {
	q, err := NewIQ(IQConfig{Rate: 96000, Tier: tier, Exact: true, Pulse: pc})
	if err != nil {
		t.Fatal(err)
	}
	r := rand.New(rand.NewPCG(1, 2))
	spp := iqShaperHz / SymbolRate
	syms := make([]float64, fitSymbols)
	raw := make([]int8, fitSymbols)
	f := make([]float64, 0, fitSymbols*spp)
	buf := make([]float64, spp+1)
	gap := 0
	for i := range syms {
		s := int8(2*r.IntN(4) - 3)
		if fitGaps {
			if gap == 0 && r.IntN(150) == 0 {
				gap = 10 + r.IntN(60)
			}
			if gap > 0 {
				gap--
				s = 0
			}
		}
		syms[i] = float64(s) / 3
		raw[i] = s
		n := q.k.symbol(buf, s)
		f = append(f, buf[:n]...)
	}
	g := append([]float64(nil), f...)
	o := newOptimizerACP(fitIters, acp, 0)
	o.noChain = noChain
	var p *predictor
	if warm != nil {
		p = &predictor{kern: warm, gain: 1}
	}
	for i := 0; i < len(g); i += spp {
		if p != nil {
			p.process(g[i:i+spp], raw[i/spp])
		}
		o.process(g[i : i+spp])
	}
	psi := make([]float64, len(f))
	var acc float64
	for i := optDelay; i < len(g); i++ {
		m := i - optDelay
		acc += (g[i] - f[m]) * 2 * math.Pi / iqShaperHz
		psi[m] = acc
	}
	nm := len(f) - optDelay - 2000
	nq := fitTaps / spp
	nu := predF * nq
	var kern [predF][fitTaps]float64
	feat := func(j int) [predF]float64 {
		var x [predSpan + 1]float64
		for k := range x {
			if j+k >= 0 && j+k < len(syms) {
				x[k] = syms[j+k]
			}
		}
		return predFeatures(x)
	}
	var sse, sst float64
	for p := range spp {
		ata := make([]float64, nu*nu)
		atb := make([]float64, nu)
		row := make([]float64, nu)
		for m := 2000 + p; m < nm; m += spp {
			if (m-fitLo-p)%spp != 0 {
				continue
			}
			jt := (m - fitLo - p) / spp
			for qq := range nq {
				ft := feat(jt - qq)
				for k := range predF {
					row[k*nq+qq] = ft[k]
				}
			}
			y := psi[m]
			for a := range nu {
				ra := row[a]
				if ra == 0 {
					continue
				}
				atb[a] += ra * y
				ar := ata[a*nu:]
				for b := a; b < nu; b++ {
					ar[b] += ra * row[b]
				}
			}
		}
		var tr float64
		for a := range nu {
			tr += ata[a*nu+a]
		}
		for a := range nu {
			ata[a*nu+a] += fitRidge * tr / float64(nu)
			for b := 0; b < a; b++ {
				ata[a*nu+b] = ata[b*nu+a]
			}
		}
		sol := cholSolve(t, ata, atb, nu)
		for k := range predF {
			for qq := range nq {
				kern[k][qq*spp+p] = sol[k*nq+qq]
			}
		}
	}
	pred := make([]float64, len(f))
	for j := range syms {
		ft := feat(j)
		for k := range predF {
			for tt := range fitTaps {
				m := j*spp + fitLo + tt
				if m < len(pred) {
					pred[m] += ft[k] * kern[k][tt]
				}
			}
		}
	}
	for m := 2000; m < nm; m++ {
		d := pred[m] - psi[m]
		sse += d * d
		sst += psi[m] * psi[m]
	}
	t.Logf("%v fit: residual %.4f of the power of the correction, rms %.4g rad", tier, sse/sst, math.Sqrt(sst/float64(nm-2000)))
	lp := newOptimizer(1).lp
	h := optLPN / 2
	full := fitTaps + optLPN - 1
	hp := make([]float64, full)
	top := fitLowPass(fitTopHz, fitTopN)
	ht := fitTopN / 2
	var out [predK][predF]float64
	for k := range predF {
		for tp := range full {
			v := 0.0
			if i := tp - fitLo; i >= 0 && i < fitTaps {
				v = kern[k][i]
			}
			for c, l := range lp {
				if i := tp + h - c - fitLo; i >= 0 && i < fitTaps {
					v -= l * kern[k][i]
				}
			}
			hp[tp] = v
		}
		for o := range predK {
			tp := o + predLo
			v := 0.0
			for c, l := range top {
				if i := tp + ht - c; i >= 0 && i < full {
					v += l * hp[i]
				}
			}
			out[o][k] = v
		}
	}
	return &out
}

func cholSolve(t *testing.T, a, b []float64, n int) []float64 {
	l := make([]float64, n*n)
	for i := range n {
		for j := 0; j <= i; j++ {
			s := a[i*n+j]
			for k := range j {
				s -= l[i*n+k] * l[j*n+k]
			}
			if i == j {
				if s <= 0 {
					t.Fatalf("not positive definite at %d", i)
				}
				l[i*n+i] = math.Sqrt(s)
			} else {
				l[i*n+j] = s / l[j*n+j]
			}
		}
	}
	y := make([]float64, n)
	for i := range n {
		s := b[i]
		for k := range i {
			s -= l[i*n+k] * y[k]
		}
		y[i] = s / l[i*n+i]
	}
	x := make([]float64, n)
	for i := n - 1; i >= 0; i-- {
		s := y[i]
		for k := i + 1; k < n; k++ {
			s -= l[k*n+i] * x[k]
		}
		x[i] = s / l[i*n+i]
	}
	return x
}
