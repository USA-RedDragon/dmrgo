//go:build !tinygo

package fsktx

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"math"
	"math/rand/v2"
	"os"
	"testing"
)

var updateKern = flag.Bool("updatekern", false, "rewrite shapekern_gen.go from a fit to the optimizer")

// Settings of the fit of the predictor kernels.
const (
	fitSymbols = 30000
	fitIters   = 30
	fitRidge   = 1e-6
	fitLo      = 80
	fitTaps    = 160
)

// TestShapeKernFit fits the predictor kernels to the corrections of the
// optimizer on random symbols, and with -updatekern writes them.
func TestShapeKernFit(t *testing.T) {
	if !*updateKern {
		t.Skip("only with -updatekern")
	}
	q, err := NewIQ(IQConfig{Rate: 96000, Tier: Tier2, Exact: true, Pulse: PulseConfig{Window: 3, Beta: 5}})
	if err != nil {
		t.Fatal(err)
	}
	r := rand.New(rand.NewPCG(1, 2))
	spp := iqShaperHz / SymbolRate
	syms := make([]float64, fitSymbols)
	f := make([]float64, 0, fitSymbols*spp)
	buf := make([]float64, spp+1)
	for i := range syms {
		s := int8(2*r.IntN(4) - 3)
		syms[i] = float64(s) / 3
		n := q.k.symbol(buf, s)
		f = append(f, buf[:n]...)
	}
	g := append([]float64(nil), f...)
	o := newOptimizer(fitIters)
	for i := 0; i < len(g); i += spp {
		o.process(g[i : i+spp])
	}
	psi := make([]float64, len(f))
	var acc float64
	for i := optDelay; i < len(g); i++ {
		m := i - optDelay
		acc += (g[i] - f[m]) * 2 * math.Pi / iqShaperHz
		psi[m] = acc
	}
	nm := len(f) - optDelay - 2000
	nq := fitTaps / spp
	nu := predF * nq
	var kern [predF][fitTaps]float64
	feat := func(j int) [predF]float64 {
		var x [predSpan + 1]float64
		for k := range x {
			if j+k >= 0 && j+k < len(syms) {
				x[k] = syms[j+k]
			}
		}
		x0, x1, x2, x3 := x[0], x[1], x[2], x[3]
		x00 := x0 * x0
		return [predF]float64{x0, x00, x00 * x0, x0 * x1, x0 * x2, x0 * x3, x00 * x1, x0 * x1 * x1, x0 * x1 * x2}
	}
	var sse, sst float64
	for p := range spp {
		ata := make([]float64, nu*nu)
		atb := make([]float64, nu)
		row := make([]float64, nu)
		for m := 2000 + p; m < nm; m += spp {
			if (m-fitLo-p)%spp != 0 {
				continue
			}
			jt := (m - fitLo - p) / spp
			for qq := range nq {
				ft := feat(jt - qq)
				for k := range predF {
					row[k*nq+qq] = ft[k]
				}
			}
			y := psi[m]
			for a := range nu {
				ra := row[a]
				if ra == 0 {
					continue
				}
				atb[a] += ra * y
				ar := ata[a*nu:]
				for b := a; b < nu; b++ {
					ar[b] += ra * row[b]
				}
			}
		}
		var tr float64
		for a := range nu {
			tr += ata[a*nu+a]
		}
		for a := range nu {
			ata[a*nu+a] += fitRidge * tr / float64(nu)
			for b := 0; b < a; b++ {
				ata[a*nu+b] = ata[b*nu+a]
			}
		}
		sol := cholSolve(t, ata, atb, nu)
		for k := range predF {
			for qq := range nq {
				kern[k][qq*spp+p] = sol[k*nq+qq]
			}
		}
	}
	pred := make([]float64, len(f))
	for j := range syms {
		ft := feat(j)
		for k := range predF {
			for tt := range fitTaps {
				m := j*spp + fitLo + tt
				if m < len(pred) {
					pred[m] += ft[k] * kern[k][tt]
				}
			}
		}
	}
	for m := 2000; m < nm; m++ {
		d := pred[m] - psi[m]
		sse += d * d
		sst += psi[m] * psi[m]
	}
	t.Logf("fit: residual %.4f of the power of the correction, rms %.4g rad", sse/sst, math.Sqrt(sst/float64(nm-2000)))
	lp := newOptimizer(1).lp
	h := optLPN / 2
	var out [predF][predK]float64
	for k := range predF {
		for tp := range predK {
			v := 0.0
			if i := tp - fitLo; i >= 0 && i < fitTaps {
				v = kern[k][i]
			}
			for c, l := range lp {
				if i := tp + h - c - fitLo; i >= 0 && i < fitTaps {
					v -= l * kern[k][i]
				}
			}
			out[k][tp] = v
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by TestShapeKernFit -updatekern; DO NOT EDIT.\n\npackage fsktx\n\n")
	b.WriteString("// shapeKern are the kernels of the predictor, one per product of symbols.\n")
	b.WriteString("var shapeKern = [predF][predK]float64{\n")
	for k := range predF {
		b.WriteString("{")
		for _, v := range out[k] {
			fmt.Fprintf(&b, "%.6g, ", v)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile("shapekern_gen.go", src, 0o644); err != nil {
		t.Fatal(err)
	}
}

func cholSolve(t *testing.T, a, b []float64, n int) []float64 {
	l := make([]float64, n*n)
	for i := range n {
		for j := 0; j <= i; j++ {
			s := a[i*n+j]
			for k := range j {
				s -= l[i*n+k] * l[j*n+k]
			}
			if i == j {
				if s <= 0 {
					t.Fatalf("not positive definite at %d", i)
				}
				l[i*n+i] = math.Sqrt(s)
			} else {
				l[i*n+j] = s / l[j*n+j]
			}
		}
	}
	y := make([]float64, n)
	for i := range n {
		s := b[i]
		for k := range i {
			s -= l[i*n+k] * y[k]
		}
		y[i] = s / l[i*n+i]
	}
	x := make([]float64, n)
	for i := n - 1; i >= 0; i-- {
		s := y[i]
		for k := i + 1; k < n; k++ {
			s -= l[k*n+i] * x[k]
		}
		x[i] = s / l[i*n+i]
	}
	return x
}
