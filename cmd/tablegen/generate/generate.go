func startFile(name string) *jen.File {
	f := jen.NewFile(name)
	f.HeaderComment("Code generated by github.com/USA-RedDragon/dmrgo/cmd/tablegen DO NOT EDIT.")
	return f
}

func writeFile(dmrRoot, dir, pkgName string, code ...jen.Code) error {
	f := startFile(pkgName)
	f.Add(code...)

	outPath := filepath.Join(dmrRoot, dir, "tables_gen.go")
	if err := f.Save(outPath); err != nil {
		return err
	}
	fmt.Println("wrote", outPath)
	return nil
}

func writeTable[T ~byte | ~int | ~uint16 | ~uint32](name string, data []T) jen.Code {
	table := jen.Var().Id(name).Op("=").Index(jen.Lit(len(data))).Add(func() jen.Code {
		switch any(data).(type) {
		case []byte:
			return jen.Byte()
		case []int:
			return jen.Int()
		case []uint16:
			return jen.Uint16()
		case []uint32:
			return jen.Uint32()
		default:
			panic("unsupported type")
		}
	}())
	literals := make([]jen.Code, len(data))
	for i, b := range data {
		literals[i] = jen.Lit(int(b))
	}
	return table.Values(literals...)
}

// writePackedBits writes the bits of data, one bit per element, as a byte
// array that holds them packed, the first bit in the most significant bit
// of byte 0.
func writePackedBits(name string, data []uint8) jen.Code {
	packed := make([]byte, (len(data)+7)/8)
	for i, b := range data {
		packed[i/8] |= (b & 1) << (7 - i%8)
	}
	literals := make([]jen.Code, len(packed))
	for i, b := range packed {
		literals[i] = jen.Id(fmt.Sprintf("0x%02X", b))
	}
	return jen.Var().Id(name).Op("=").Index(jen.Lit(len(packed))).Byte().Values(literals...)
}

func writeTable2D[T ~byte | ~int | ~int8 | ~uint16 | ~uint32 | ~uint64](name string, data [][]T) jen.Code {
	if len(data) == 0 {
		return jen.Null()
	}
	innerLen := len(data[0])

	elemType := func() jen.Code {
		switch any(data[0]).(type) {
		case []byte:
			return jen.Byte()
		case []int:
			return jen.Int()
		case []int8:
			return jen.Int8()
		case []uint16:
			return jen.Uint16()
		case []uint32:
			return jen.Uint32()
		case []uint64:
			return jen.Uint64()
		default:
			panic("unsupported type")
		}
	}()

	table := jen.Var().Id(name).Op("=").Index(jen.Lit(len(data))).Index(jen.Lit(innerLen)).Add(elemType)

	rows := make([]jen.Code, len(data))
	for i, row := range data {
		literals := make([]jen.Code, len(row))
		for j, val := range row {
			if v, ok := any(val).(uint64); ok {
				literals[j] = jen.Op(fmt.Sprintf("%#016x", v))
			} else {
				literals[j] = jen.Lit(int(val))
			}
		}
		rows[i] = jen.Values(literals...)
	}

	return table.Values(rows...)
}
