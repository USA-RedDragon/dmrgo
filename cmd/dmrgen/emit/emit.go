// resolveImportPath converts a short package name (e.g. "enums") to a full import path.
func resolveImportPath(pkgName, sourceFile string) string {
	// Map well-known package names to full import paths
	knownPkgs := map[string]string{
		"enums":            "github.com/USA-RedDragon/dmrgo/v2/enums",
		"bit":              "github.com/USA-RedDragon/dmrgo/v2/bit",
		"fec":              "github.com/USA-RedDragon/dmrgo/v2/fec",
		"layer3":           "github.com/USA-RedDragon/dmrgo/v2/layer3",
		"golay":            "github.com/USA-RedDragon/dmrgo/v2/fec/golay",
		"quadraticResidue": qrPkg,
		"reedSolomon":      "github.com/USA-RedDragon/dmrgo/v2/fec/reedsolomon",
		"bptc":             "github.com/USA-RedDragon/dmrgo/v2/fec/bptc",
		"trellis":          "github.com/USA-RedDragon/dmrgo/v2/fec/trellis",
		"hamming":          "github.com/USA-RedDragon/dmrgo/v2/fec/hamming",
		"vocoder":          "github.com/USA-RedDragon/dmrgo/v2/vocoder",
	}
	if p, ok := knownPkgs[pkgName]; ok {
		return p
	}
	// Fall back: assume it's a relative sibling package
	dir := filepath.Dir(sourceFile)
	return "github.com/USA-RedDragon/dmrgo/" + filepath.Join(dir, pkgName)
}

// GenerateFile produces the _decode_gen.go content for a set of PDU structs.
func GenerateFile(pdus []parse.PDUStruct, pkgName string) (*File, error) {
	f := NewFile(pkgName)

	// Build header comment, including spec references when available.
	header := "Code generated by dmrgen."
	var specRefs []string
	seen := map[string]bool{}
	for _, pdu := range pdus {
		if pdu.SpecRef != "" && !seen[pdu.SpecRef] {
			specRefs = append(specRefs, pdu.SpecRef)
			seen[pdu.SpecRef] = true
		}
	}
	if len(specRefs) > 0 {
		header += "\n"
		for _, ref := range specRefs {
			header += "\n" + ref
		}
		header += "\n"
	}
	header += "\nDO NOT EDIT."
	f.HeaderComment(header)

	for _, pdu := range pdus {
		if err := emitDecode(f, pdu); err != nil {
			return nil, fmt.Errorf("generating decode for %s: %w", pdu.Name, err)
		}
		f.Line()
		if err := emitEncode(f, pdu); err != nil {
			return nil, fmt.Errorf("generating encode for %s: %w", pdu.Name, err)
		}
		f.Line()
		emitString(f, pdu)
	}

	return f, nil
}

// emitDecode generates a DecodeXxx function for a PDU struct.
func emitDecode(f *File, pdu parse.PDUStruct) error {
	funcName := "Decode" + pdu.Name
	inputSize := pdu.InputSize

	// Add spec reference comment above the function if available.
	if pdu.SpecRef != "" {
		f.Comment(funcName + " decodes a " + pdu.Name + " per " + pdu.SpecRef)
	}

	codec, err := resolveCodec(pdu)
	if err != nil {
		return err
	}
	if codec != nil {
		inputSize = codec.InputSize
	}

	var genErr error
	// func DecodeXxx(data [N]bit.Bit) Xxx {
	params := []Code{Id("data").Index(Lit(inputSize)).Qual(bitPkg, "Bit")}
	for _, in := range pdu.Inputs {
		field := pdu.FieldByName(in)
		if field == nil {
			return fmt.Errorf("dmr:input %q is not a field", in)
		}
		params = append(params, Id(inputParamName(in)).Add(qualType(*field, pdu)))
	}

	f.Func().Id(funcName).Params(params...).Id(pdu.Name).BlockFunc(func(g *Group) {
		g.Var().Id("result").Id(pdu.Name)
		for _, in := range pdu.Inputs {
			g.Id("result").Dot(in).Op("=").Id(inputParamName(in))
		}
		g.Qual(bitPkg, "Mask").Call(Id("data").Index(Empty(), Empty()))

		hasCRC := pdu.CRC != nil
		hasPackedFEC := codec != nil && codec.PackedBytes
		hasBitFEC := codec != nil && !codec.PackedBytes
		if hasCRC || hasPackedFEC {
			// Check if the CRC is byte-level (needs packing) or bit-level
			isBitCRC := false
			if hasCRC {
				if algo, ok := crcAlgorithms[pdu.CRC.Algorithm]; ok {
					isBitCRC = algo.BitLevel
				}
			}
			if !isBitCRC {
				// Byte-level CRC and packed-bytes FEC need bit packing first
				totalBytes := inputSize / 8
				emitBitPacking(g, totalBytes)
			}
		}

		switch {
		case hasCRC:
			if err := emitCRCCheck(g, pdu, inputSize); err != nil {
				genErr = err
				return
			}
		case hasPackedFEC:
			if err := emitFECMask(g, pdu, codec, Id("result"), "_packedBytes", nil); err != nil {
				genErr = err
				return
			}
			emitPackedFECDecode(g, codec)
		case hasBitFEC:
			// Bit-level FEC (Golay, QR): operates directly on bit arrays
			g.Var().Id("corrected").Index(Lit(codec.InputSize)).Qual(bitPkg, "Bit")
			g.List(Id("corrected"), Id("result").Dot(fecFieldName)).Op("=").Qual(codec.ImportPath, codec.DecodeFn).Call(Id("data"))
			g.If(Op("!").Id("result").Dot(fecFieldName).Dot("Uncorrectable")).Block(
				Id("data").Op("=").Id("corrected"),
			)
		}

		// Emit field extractions (regular fields first, then dispatch)
		var dispatchFields []parse.Field
		for _, field := range pdu.Fields {
			if field.Skip {
				continue // skip dmr:"-" fields (DataType, FEC, crc, etc.)
			}
			if field.Kind == parse.FieldDispatch {
				dispatchFields = append(dispatchFields, field)
				continue
			}
			if field.Fallback {
				continue
			}
			emitFieldDecode(g, field, pdu)
		}

		// Emit dispatch switch if there are dispatch fields
		if len(dispatchFields) > 0 {
			if err := emitDispatchSwitch(g, dispatchFields, pdu); err != nil {
				genErr = err
				return
			}
		}

		g.Return(Id("result"))
	})

	return genErr
}

// resolveCodec looks up the FEC codec and CRC algorithm of a PDU and checks
// that its fields fit the codec's data bits. It returns a nil codec for PDUs
// without a dmr:fec directive.
func resolveCodec(pdu parse.PDUStruct) (*FECCodecInfo, error) {
	if pdu.CRC != nil {
		if _, ok := crcAlgorithms[pdu.CRC.Algorithm]; !ok {
			return nil, fmt.Errorf("unknown CRC algorithm: %q", pdu.CRC.Algorithm)
		}
	}
	if pdu.FEC == nil {
		return nil, nil //nolint:nilnil // no codec is a valid result
	}
	c, ok := fecCodecs[pdu.FEC.Codec]
	if !ok {
		return nil, fmt.Errorf("unknown FEC codec: %s", pdu.FEC.Codec)
	}
	if pdu.CRC != nil {
		return nil, errors.New("dmr:fec and dmr:crc cannot be combined")
	}
	dataBits := c.DataBits
	if c.PackedBytes {
		dataBits = c.DataBytes * 8
	}
	if pdu.InputSize > dataBits {
		return nil, fmt.Errorf("fields span %d bits but %s carries %d data bits", pdu.InputSize, pdu.FEC.Codec, dataBits)
	}
	return &c, nil
}

// emitBitPacking generates code to pack bit.Bit array into []byte.
func emitBitPacking(g *Group, totalBytes int) {
	// var _packedBytes [N]byte
	g.Var().Id("_packedBytes").Index(Lit(totalBytes)).Byte()
	// for i := range N { for j := range 8 { _packedBytes[i] <<= 1; _packedBytes[i] |= byte(data[i*8+j]) } }
	g.For(Id("i").Op(":=").Range().Lit(totalBytes)).Block(
		For(Id("j").Op(":=").Range().Lit(8)).Block(
			Id("_packedBytes").Index(Id("i")).Op("<<=").Lit(1),
			Id("_packedBytes").Index(Id("i")).Op("|=").Byte().Call(
				Id("data").Index(Id("i").Op("*").Lit(8).Op("+").Id("j")),
			),
		),
	)
}

// emitCRCCheck generates CRC validation code for both byte-level (CRC-CCITT) and bit-level (CRC-8) CRCs.
func emitCRCCheck(g *Group, pdu parse.PDUStruct, inputSize int) error {
	crcDir := pdu.CRC

	algo, ok := crcAlgorithms[crcDir.Algorithm]
	if !ok {
		return fmt.Errorf("unknown CRC algorithm: %q", crcDir.Algorithm)
	}
	if algo.BitLevel {
		// Bit-level CRC (e.g. CRC-8): operates on data[:] directly, no byte packing
		dataBits := inputSize - algo.CRCBits
		g.Id("_crc").Op(":=").Uint8().Call(Qual(bitPkg, "Uint").Call(Id("data").Index(Lit(dataBits), Empty())))
		g.Id("result").Dot(fecFieldName).Dot("Uncorrectable").Op("=").
			Op("!").Qual(crcPkg, algo.CheckFn).Call(Id("data").Index(Empty(), Lit(dataBits)), Id("_crc"))
		return nil
	}

	// Byte-level CRC (CRC-CCITT): operates on packed bytes
	// Apply XOR mask if specified
	if crcDir.HasMask {
		highByte, lowByte := maskBytes(crcDir.Mask)
		totalBytes := inputSize / 8
		g.Id("_packedBytes").Index(Lit(totalBytes - 2)).Op("^=").Lit(highByte)
		g.Id("_packedBytes").Index(Lit(totalBytes - 1)).Op("^=").Lit(lowByte)
	}

	// Read the CRC from the (possibly masked) packed bytes, then check it
	totalBytes := inputSize / 8
	g.Id("_crc").Op(":=").
		Uint16().Call(Id("_packedBytes").Index(Lit(totalBytes - 2))).Op("<<").Lit(8).
		Op("|").Uint16().Call(Id("_packedBytes").Index(Lit(totalBytes - 1)))
	g.Id("result").Dot(fecFieldName).Dot("Uncorrectable").Op("=").
		Op("!").Qual(crcPkg, algo.CheckFn).Call(Id("_packedBytes").Index(Empty(), Lit(totalBytes-2)), Id("_crc"))
	return nil
}

// emitFECMask XORs the FEC parity bytes of buf with the mask selected by the
// dmr:fec_mask field of src (ETSI TS 102 361-1 B.3.12, Table B.21). If
// noMask is not nil, it is emitted for a field value with no mask.
func emitFECMask(g *Group, pdu parse.PDUStruct, codec *FECCodecInfo, src *Statement, buf string, noMask Code) error {
	if pdu.FECMask == nil {
		return nil
	}
	if !codec.PackedBytes {
		return fmt.Errorf("dmr:fec_mask is only supported for packed-byte codecs, not %s", pdu.FEC.Codec)
	}
	parityBytes := codec.TotalBytes - codec.DataBytes
	var genErr error
	g.Switch(src.Clone().Dot(pdu.FECMask.Field)).BlockFunc(func(sw *Group) {
		for _, m := range pdu.FECMask.Masks {
			if m.Mask>>(8*parityBytes) != 0 {
				genErr = fmt.Errorf("dmr:fec_mask %#x is wider than %d parity bytes", m.Mask, parityBytes)
				return
			}
			var stmts []Code
			for k := range parityBytes {
				b := (m.Mask >> (8 * (parityBytes - 1 - k))) & 0xFF
				stmts = append(stmts, Id(buf).Index(Lit(codec.DataBytes+k)).Op("^=").Id(fmt.Sprintf("0x%02X", b)))
			}
			sw.Case(emitDispatchConstant(m.Value, pdu)).Block(stmts...)
		}
		if noMask != nil {
			sw.Default().Block(noMask)
		}
	})
	return genErr
}

// emitPackedFECDecode generates packed-bytes FEC (e.g. Reed-Solomon) decode code.
func emitPackedFECDecode(g *Group, codec *FECCodecInfo) {
	g.Var().Id("_fecData").Index(Lit(codec.DataBytes)).Byte()
	g.List(Id("_fecData"), Id("result").Dot(fecFieldName)).Op("=").Qual(codec.ImportPath, codec.DecodeFn).Call(Id("_packedBytes"))

	// If corrected, unpack corrected data bytes back into the data bit array
	g.If(Op("!").Id("result").Dot(fecFieldName).Dot("Uncorrectable")).Block(
		For(Id("i").Op(":=").Range().Lit(codec.DataBytes)).Block(
			For(Id("j").Op(":=").Range().Lit(8)).Block(
				Id("data").Index(Id("i").Op("*").Lit(8).Op("+").Id("j")).Op("=").
					Qual(bitPkg, "Bit").Call(
					Parens(Id("_fecData").Index(Id("i")).Op(">>").
						Parens(Lit(7).Op("-").Id("j"))).Op("&").Lit(1),
				),
			),
		),
	)
}

// emitDispatchSwitch generates a switch statement that dispatches on a field value
// and decodes the appropriate sub-PDU into a pointer field.
// When multiple fields share the same dispatch value, a secondary guard condition
// (parsed from the `when:` modifier) is used to disambiguate them via if/else.
func emitDispatchSwitch(g *Group, fields []parse.Field, pdu parse.PDUStruct) error {
	bitStart := fields[0].BitStart
	bitEnd := fields[0].BitEnd
	arraySize := bitEnd - bitStart + 1

	tmpVar := "_dispatchBits"
	g.Var().Id(tmpVar).Index(Lit(arraySize)).Qual(bitPkg, "Bit")
	g.Copy(Id(tmpVar).Index(Empty(), Empty()), Id("data").Index(Lit(bitStart), Lit(bitEnd+1)))

	var raw []Code
	if fb := fallbackField(pdu); fb != nil {
		raw = []Code{packRaw(Id("result").Dot(fb.Name), Id(tmpVar), 0, fb.BitWidth)}
	}
	stmt, err := dispatchSelect(fields, pdu, func(field parse.Field) []Code {
		return dispatchDecodeBlock(field, tmpVar)
	}, raw)
	if err != nil {
		return err
	}
	g.Add(stmt)
	return nil
}

// dispatchSelect builds the statement that selects a dispatch field from the
// decoded fields of result. It emits pick for the selected field and raw
// (if not nil) when no field is selected.
func dispatchSelect(fields []parse.Field, pdu parse.PDUStruct, pick func(parse.Field) []Code, raw []Code) (*Statement, error) {
	// Group fields by their dispatch values to detect shared-value cases.
	type dispatchGroup struct {
		values []string
		fields []parse.Field
	}
	var groups []dispatchGroup
	groupIndex := map[string]int{}
	for _, field := range fields {
		key := strings.Join(field.DispatchValues, "|")
		if idx, ok := groupIndex[key]; ok {
			groups[idx].fields = append(groups[idx].fields, field)
		} else {
			groupIndex[key] = len(groups)
			groups = append(groups, dispatchGroup{values: field.DispatchValues, fields: []parse.Field{field}})
		}
	}

	var genErr error
	sw := Switch(Id("result").Dot(fields[0].DispatchFieldName)).BlockFunc(func(sw *Group) {
		for _, grp := range groups {
			caseValues := make([]Code, len(grp.values))
			for i, val := range grp.values {
				caseValues[i] = emitDispatchConstant(val, pdu)
			}

			if len(grp.fields) == 1 && grp.fields[0].When == nil {
				sw.Case(caseValues...).Block(pick(grp.fields[0])...)
				continue
			}
			sw.Case(caseValues...).BlockFunc(func(caseBody *Group) {
				if err := emitGuardedDispatch(caseBody, grp.fields, pick, raw); err != nil && genErr == nil {
					genErr = err
				}
			})
		}
		if raw != nil {
			sw.Default().Block(raw...)
		}
	})
	if genErr != nil {
		return nil, genErr
	}

	if pdu.DispatchIf == nil {
		return sw, nil
	}
	cond, err := emitGuardCondition(pdu.DispatchIf)
	if err != nil {
		return nil, fmt.Errorf("dmr:dispatch_if: %w", err)
	}
	stmt := If(cond).Block(sw)
	if raw != nil {
		stmt.Else().Block(raw...)
	}
	return stmt, nil
}

// fallbackField returns the raw field that holds undispatched payloads, or nil.
func fallbackField(pdu parse.PDUStruct) *parse.Field {
	for i := range pdu.Fields {
		if pdu.Fields[i].Fallback {
			return &pdu.Fields[i]
		}
	}
	return nil
}

func dispatchDecodeBlock(field parse.Field, tmpVar string) []Code {
	return []Code{
		Id("_decoded").Op(":=").Id("Decode" + dispatchTypeName(field)).Call(Id(tmpVar)),
		Id("result").Dot(field.Name).Op("=").Op("&").Id("_decoded"),
	}
}

func dispatchTypeName(field parse.Field) string {
	if field.IsPointer && field.PointedType != "" {
		return field.PointedType
	}
	return field.TypeName
}

// emitGuardedDispatch emits an if/else chain for dispatch fields that share the
// same primary dispatch value. Fields with a `when:` guard are emitted as `if`
// conditions; the unguarded field (if any) becomes the final `else` branch,
// otherwise raw (if not nil) does.
func emitGuardedDispatch(g *Group, fields []parse.Field, pick func(parse.Field) []Code, raw []Code) error {
	var guarded []parse.Field
	var fallback *parse.Field
	for i := range fields {
		if fields[i].When != nil {
			guarded = append(guarded, fields[i])
			continue
		}
		if fallback != nil {
			return fmt.Errorf("dispatch fields %s and %s share values and neither has a when: guard", fallback.Name, fields[i].Name)
		}
		fb := fields[i]
		fallback = &fb
	}

	// Build the guard chain as a single jennifer *Statement so that
	// "} else {" stays on one line.
	var chain *Statement
	for i, field := range guarded {
		guardCond, err := emitGuardCondition(field.When)
		if err != nil {
			return fmt.Errorf("field %s: %w", field.Name, err)
		}
		if i == 0 {
			chain = If(guardCond).Block(pick(field)...)
		} else {
			chain.Else().If(guardCond).Block(pick(field)...)
		}
	}
	switch {
	case fallback != nil:
		chain.Else().Block(pick(*fallback)...)
	case raw != nil:
		chain.Else().Block(raw...)
	}
	g.Add(chain)
	return nil
}

// emitGuardCondition generates the Code for a guard condition on the decoded result,
// e.g. result.AppendedBlocks == 0 or result.TrunkingMode == true.
func emitGuardCondition(guard *parse.Guard) (*Statement, error) {
	lhs := Id("result").Dot(guard.Field)

	var val *Statement
	switch guard.Value {
	case "true", "false":
		if (guard.Value == "true") == (guard.Op == "==") {
			return lhs, nil
		}
		return Op("!").Add(lhs), nil
	default:
		n, err := strconv.Atoi(guard.Value)
		if err != nil {
			return nil, fmt.Errorf("guard value %q is not an integer or bool", guard.Value)
		}
		val = Lit(n)
	}

	switch guard.Op {
	case "==", "!=":
		return lhs.Op(guard.Op).Add(val), nil
	default:
		return nil, fmt.Errorf("unsupported guard operator %q", guard.Op)
	}
}

// emitDispatchConstant generates the jennifer Code for a dispatch constant reference.
// If the value contains a ".", it's a cross-package constant (e.g. "enums.FLCOGroupVoiceChannelUser").
// Otherwise it's a same-package constant (e.g. "CSBKBSOutboundActivationPDU").
func emitDispatchConstant(val string, pdu parse.PDUStruct) Code {
	if idx := strings.LastIndex(val, "."); idx >= 0 {
		pkg := val[:idx]
		name := val[idx+1:]
		importPath := resolveImportPath(pkg, pdu.SourceFile)
		return Qual(importPath, name)
	}
	return Id(val)
}

// emitString generates a String() method for a PDU struct.
// Simple structs (no dispatch/stride) use a single fmt.Sprintf.
// Structs with dispatch or stride fields use string concatenation.
func emitString(f *File, pdu parse.PDUStruct) {
	// Determine if we need concatenation mode
	hasDispatch := false
	hasStride := false
	for _, field := range pdu.Fields {
		if field.Skip {
			continue
		}
		if field.Kind == parse.FieldDispatch {
			hasDispatch = true
		}
		if field.Stride > 0 && field.ArrayLen > 0 {
			hasStride = true
		}
	}

	if hasDispatch || hasStride {
		emitStringConcat(f, pdu)
	} else {
		emitStringSprintf(f, pdu)
	}
}

// emitStringSprintf generates a String method using a single fmt.Sprintf call.
func emitStringSprintf(f *File, pdu parse.PDUStruct) {
	var formatParts []string
	var args []Code

	for _, field := range pdu.Fields {
		fmtToken, fmtArgs := toStringFieldFormat(field, pdu)
		if fmtToken == "" {
			continue
		}
		formatParts = append(formatParts, field.Name+": "+fmtToken)
		args = append(args, fmtArgs...)
	}

	formatStr := pdu.Name + "{ " + strings.Join(formatParts, ", ") + " }"
	allArgs := append([]Code{Lit(formatStr)}, args...)

	f.Func().Params(Id("s").Op("*").Id(pdu.Name)).Id("String").Params().String().Block(
		Return(Qual("fmt", "Sprintf").Call(allArgs...)),
	)
}

// emitStringConcat generates a String method using string concatenation for dispatch/stride fields.
func emitStringConcat(f *File, pdu parse.PDUStruct) {
	f.Func().Params(Id("s").Op("*").Id(pdu.Name)).Id("String").Params().String().BlockFunc(func(g *Group) {
		g.Id("_ret").Op(":=").Lit(pdu.Name + "{ ")

		// Collect dispatch fields for later, emit regular fields inline
		var dispatchFields []parse.Field
		regularParts := []string{}
		regularArgs := []Code{}

		for _, field := range pdu.Fields {
			if field.Skip {
				fmtToken, fmtArgs := toStringFieldFormat(field, pdu)
				if fmtToken == "" {
					continue
				}
				regularParts = append(regularParts, field.Name+": "+fmtToken)
				regularArgs = append(regularArgs, fmtArgs...)
				continue
			}
			if field.Kind == parse.FieldDispatch {
				dispatchFields = append(dispatchFields, field)
				continue
			}
			if field.Fallback {
				continue
			}
			if field.Stride > 0 && field.ArrayLen > 0 {
				// Emit the regular fields collected so far
				if len(regularParts) > 0 {
					fmtStr := strings.Join(regularParts, ", ") + ", "
					allArgs := append([]Code{Lit(fmtStr)}, regularArgs...)
					g.Id("_ret").Op("+=").Qual("fmt", "Sprintf").Call(allArgs...)
					regularParts = nil
					regularArgs = nil
				}
				// Emit stride array iteration
				g.Id("_ret").Op("+=").Lit(field.Name + ": [")
				g.For(Id("_i").Op(":=").Range().Id("s").Dot(field.Name)).Block(
					If(Id("_i").Op(">").Lit(0)).Block(
						Id("_ret").Op("+=").Lit(", "),
					),
					Id("_ret").Op("+=").Id("s").Dot(field.Name).Index(Id("_i")).Dot("String").Call(),
				)
				g.Id("_ret").Op("+=").Lit("]")
				continue
			}
			fmtToken, fmtArgs := toStringFieldFormat(field, pdu)
			if fmtToken == "" {
				continue
			}
			regularParts = append(regularParts, field.Name+": "+fmtToken)
			regularArgs = append(regularArgs, fmtArgs...)
		}

		// Emit any remaining regular fields before dispatch
		if len(regularParts) > 0 && len(dispatchFields) > 0 {
			fmtStr := strings.Join(regularParts, ", ") + ", "
			allArgs := append([]Code{Lit(fmtStr)}, regularArgs...)
			g.Id("_ret").Op("+=").Qual("fmt", "Sprintf").Call(allArgs...)
			regularParts = nil
			regularArgs = nil
		}

		// Emit dispatch nil-check chain
		if len(dispatchFields) > 0 {
			g.Switch().BlockFunc(func(sw *Group) {
				for _, field := range dispatchFields {
					sw.Case(Id("s").Dot(field.Name).Op("!=").Nil()).Block(
						Id("_ret").Op("+=").Id("s").Dot(field.Name).Dot("String").Call(),
					)
				}
				if fb := fallbackField(pdu); fb != nil {
					sw.Default().Block(
						Id("_ret").Op("+=").Qual("fmt", "Sprintf").Call(Lit(fb.Name+": %x"), Id("s").Dot(fb.Name)),
					)
				}
			})
		}

		// Emit any remaining regular fields after dispatch (like FEC)
		if len(regularParts) > 0 {
			fmtStr := ", " + strings.Join(regularParts, ", ")
			allArgs := append([]Code{Lit(fmtStr)}, regularArgs...)
			g.Id("_ret").Op("+=").Qual("fmt", "Sprintf").Call(allArgs...)
		}

		g.Id("_ret").Op("+=").Lit(" }")
		g.Return(Id("_ret"))
	})
}

// toStringFieldFormat returns the fmt format token and arguments for a field in String.
// Returns empty string if the field should be skipped.
func toStringFieldFormat(field parse.Field, pdu parse.PDUStruct) (string, []Code) {
	src := Id("s").Dot(field.Name)

	if field.Skip {
		// Handle dmr:"-" fields
		switch field.Name {
		case fecFieldName:
			return "{BitsChecked: %d, ErrorsCorrected: %d, Uncorrectable: %t}", []Code{
				src.Clone().Dot("BitsChecked"),
				src.Clone().Dot("ErrorsCorrected"),
				src.Clone().Dot("Uncorrectable"),
			}
		default:
			if pdu.IsInput(field.Name) {
				return "%v", []Code{src.Clone()}
			}
			// Skip unexported and other skip fields
			return "", nil
		}
	}

	switch field.Kind {
	case parse.FieldBool:
		return "%t", []Code{src}
	case parse.FieldUint:
		return "%d", []Code{src}
	case parse.FieldInt:
		return "%d", []Code{src}
	case parse.FieldEnum:
		return "%s", []Code{src}
	case parse.FieldRaw:
		return "%x", []Code{src}
	case parse.FieldPacked:
		return "%v", []Code{src}
	case parse.FieldDelegate:
		if field.DelegateNoPtr {
			return "%s", []Code{src}
		}
		// Struct delegate: call String()
		return "%s", []Code{src.Clone().Dot("String").Call()}
	case parse.FieldLongitude, parse.FieldLatitude:
		return "%f", []Code{src}
	case parse.FieldDispatch:
		// Handled separately in concat mode
		return "", nil
	default:
		return "%v", []Code{src}
	}
}

// emitFieldDecode generates the decode logic for a single field.
func emitFieldDecode(g *Group, field parse.Field, pdu parse.PDUStruct) {
	target := Id("result").Dot(field.Name)

	if len(field.ExtraBitRanges) > 0 {
		emitNonContiguousDecode(g, field, pdu)
		return
	}

	switch field.Kind {
	case parse.FieldBool:
		g.Add(target).Op("=").Id("data").Index(Lit(field.BitStart)).Op("==").Lit(1)

	case parse.FieldUint, parse.FieldEnum:
		g.Add(target).Op("=").Add(castUint(field, pdu, readUint(field)))

	case parse.FieldInt:
		if field.Signed {
			g.Add(target).Op("=").Add(qualType(field, pdu)).Call(signExtend(field, Uint32().Call(readUint(field))))
			break
		}
		g.Add(target).Op("=").Add(castUint(field, pdu, readUint(field)))

	case parse.FieldRaw:
		g.Add(packRaw(target, Id("data"), field.BitStart, field.BitWidth))

	case parse.FieldPacked:
		// Pack bits into bytes using bit.Pack
		packed := Qual(bitPkg, "Pack").Call(
			Id("data").Index(Lit(field.BitStart), Lit(field.BitEnd+1)),
		)
		if isFixedArray(field.GoType) {
			// Fixed-size array: must use copy
			g.Copy(target.Clone().Index(Empty(), Empty()), packed)
		} else {
			g.Add(target).Op("=").Add(packed)
		}

	case parse.FieldDelegate:
		var importPath string
		if field.IsQualified {
			importPath = resolveImportPath(field.TypePkg, pdu.SourceFile)
		}

		switch {
		case field.Stride > 0 && field.ArrayLen > 0:
			// Array delegate with stride: generate a loop calling DecodeXxx
			decodeFn := "Decode" + field.TypeName
			tmpVar := "_elemBits"
			g.For(Id("_i").Op(":=").Lit(0), Id("_i").Op("<").Lit(field.ArrayLen), Id("_i").Op("++")).Block(
				Var().Id(tmpVar).Index(Lit(field.Stride)).Qual(bitPkg, "Bit"),
				Copy(Id(tmpVar).Index(Empty(), Empty()), Id("data").Index(
					Lit(field.BitStart).Op("+").Id("_i").Op("*").Lit(field.Stride),
					Lit(field.BitStart).Op("+").Id("_i").Op("*").Lit(field.Stride).Op("+").Lit(field.Stride),
				)),
				func() Code {
					var call Code
					if field.IsQualified {
						call = Qual(importPath, decodeFn).Call(Id(tmpVar))
					} else {
						call = Id(decodeFn).Call(Id(tmpVar))
					}
					return target.Clone().Index(Id("_i")).Op("=").Add(call)
				}(),
			)
		case field.DelegateNoPtr:
			// noptr delegates are integer typedefs: extract and convert
			g.Add(target).Op("=").Add(castUint(field, pdu, readUint(field)))
		default:
			// Struct delegate: call generated DecodeXxx function
			decodeFnName := "Decode" + field.TypeName
			arraySize := field.BitEnd - field.BitStart + 1
			tmpVar := "_" + strings.ToLower(field.Name[:1]) + field.Name[1:] + "Bits"

			g.Var().Id(tmpVar).Index(Lit(arraySize)).Qual(bitPkg, "Bit")
			g.Copy(Id(tmpVar).Index(Empty(), Empty()), Id("data").Index(Lit(field.BitStart), Lit(field.BitEnd+1)))

			var decodeFnCall Code
			if field.IsQualified {
				decodeFnCall = Qual(importPath, decodeFnName).Call(Id(tmpVar))
			} else {
				decodeFnCall = Id(decodeFnName).Call(Id(tmpVar))
			}
			g.Add(target).Op("=").Add(decodeFnCall)
		}

	case parse.FieldLongitude, parse.FieldLatitude:
		// Two's complement value scaled by span/2^width (ETSI TS 102 361-2 7.2.16/7.2.17)
		g.Add(target).Op("=").Float64().Call(signExtend(field, Uint32().Call(readUint(field)))).
			Op("*").Lit(coordSpan(field)).Op("/").Parens(Lit(1).Op("<<").Lit(field.BitWidth))

	case parse.FieldDispatch:
		// Dispatch fields are handled separately in emitDispatchSwitch
		// (no-op here — they are emitted after all regular fields)
	}
}

// emitEncode generates the Encode method of a PDU struct.
// For FEC-protected PDUs, the output includes FEC parity (full codeword).
// The method returns an error when a field value does not fit its bits.
func emitEncode(f *File, pdu parse.PDUStruct) error {
	// Add spec reference comment above the method if available.
	if pdu.SpecRef != "" {
		f.Comment("Encode encodes a " + pdu.Name + " per " + pdu.SpecRef)
	}

	codec, err := resolveCodec(pdu)
	if err != nil {
		return err
	}

	hasCRC := pdu.CRC != nil
	hasPackedFEC := codec != nil && codec.PackedBytes
	hasBitFEC := codec != nil && !codec.PackedBytes

	// Output is the full codeword size
	outputSize := pdu.InputSize
	if codec != nil {
		outputSize = codec.InputSize
	}
	enc := encoder{pdu: pdu, size: outputSize}

	var genErr error
	f.Func().Params(Id("s").Op("*").Id(pdu.Name)).Id("Encode").Params().Params(
		Index(Lit(outputSize)).Qual(bitPkg, "Bit"),
		Error(),
	).BlockFunc(func(g *Group) {
		switch {
		case hasBitFEC:
			// Bit-level FEC (Golay, QR): build data bits, then FEC-encode
			g.Var().Id("data").Index(Lit(codec.DataBits)).Qual(bitPkg, "Bit")
			if err := enc.fields(g); err != nil {
				genErr = err
				return
			}
			g.Return(Qual(codec.ImportPath, codec.EncodeFn).Call(Id("data")), Nil())
		case hasCRC || hasPackedFEC:
			// CRC or packed FEC: build data bits, then pack+CRC/RS-encode
			g.Var().Id("data").Index(Lit(outputSize)).Qual(bitPkg, "Bit")
			if err := enc.fields(g); err != nil {
				genErr = err
				return
			}
			if hasCRC {
				emitCRCEncode(g, pdu, outputSize)
			}
			if hasPackedFEC {
				if err := emitPackedFECEncode(g, enc, codec); err != nil {
					genErr = err
					return
				}
			}
			g.Return(Id("data"), Nil())
		default:
			g.Var().Id("data").Index(Lit(outputSize)).Qual(bitPkg, "Bit")
			if err := enc.fields(g); err != nil {
				genErr = err
				return
			}
			g.Return(Id("data"), Nil())
		}
	})
	return genErr
}

// encoder carries the PDU and output size while emitting an Encode body.
type encoder struct {
	pdu  parse.PDUStruct
	size int
}

// fail returns a statement that returns a zero codeword and the given error.
func (e encoder) fail(err Code) *Statement {
	return Return(Index(Lit(e.size)).Qual(bitPkg, "Bit").Values(), err)
}

// failRange returns a statement that returns a zero codeword and a
// *bit.FieldRangeError for field. extra adds Min and Max for a range check.
func (e encoder) failRange(field parse.Field, extra Dict) *Statement {
	d := Dict{
		Id("Type"):  Lit(e.pdu.Name),
		Id("Field"): Lit(field.Name),
		Id("Value"): Id("s").Dot(field.Name),
		Id("Bits"):  Lit(field.BitWidth),
	}
	if field.Signed || field.Kind == parse.FieldLongitude || field.Kind == parse.FieldLatitude {
		d[Id("Signed")] = True()
	}
	for k, v := range extra {
		d[k] = v
	}
	return e.fail(Op("&").Qual(bitPkg, "FieldRangeError").Values(d))
}

// fields emits encoding for all fields (regular + dispatch).
// Dispatch fields are encoded FIRST so their wide copy (e.g. data[0:80])
// doesn't overwrite the outer struct's non-dispatch fields (e.g. Format,
// AppendedBlocks) that may share the same bit range.
func (e encoder) fields(g *Group) error {
	var regularFields []parse.Field
	var dispatchFields []parse.Field
	for _, field := range e.pdu.Fields {
		if field.Skip {
			continue // skip dmr:"-" fields
		}
		switch {
		case field.Kind == parse.FieldDispatch:
			dispatchFields = append(dispatchFields, field)
		case field.Fallback:
		default:
			regularFields = append(regularFields, field)
		}
	}
	// Dispatch first — sub-PDU copies the full payload range.
	if len(dispatchFields) > 0 {
		e.payload(g, dispatchFields)
		e.dispatch(g, dispatchFields)
	}
	// Then non-dispatch fields overwrite their specific bit positions.
	for _, field := range regularFields {
		if field.NoEncode {
			continue // decoded for guard conditions but not encoded (sub-PDU handles these bits)
		}
		e.field(g, field)
	}
	for i, c := range e.pdu.Consts {
		e.constant(g, c, i)
	}
	if len(dispatchFields) > 0 {
		return e.checkPayload(g, dispatchFields)
	}
	return nil
}

// payload sets _payload to the name of the one dispatch field that is set,
// or "" if none is, and fails if more than one is set.
func (e encoder) payload(g *Group, fields []parse.Field) {
	g.Id("_payload").Op(":=").Lit("")
	g.For(List(Id("_"), Id("_p")).Op(":=").Range().Index(Op("...")).Struct(
		Id("name").String(),
		Id("set").Bool(),
	).ValuesFunc(func(vals *Group) {
		for _, field := range fields {
			vals.Line().Values(Lit(field.Name), Id("s").Dot(field.Name).Op("!=").Nil())
		}
		vals.Line()
	})).Block(
		If(Op("!").Id("_p").Dot("set")).Block(Continue()),
		If(Id("_payload").Op("!=").Lit("")).Block(
			e.fail(Qual("fmt", "Errorf").Call(Lit(e.pdu.Name+": %s and %s are both set"), Id("_payload"), Id("_p").Dot("name"))),
		),
		Id("_payload").Op("=").Id("_p").Dot("name"),
	)
}

// checkPayload fails if the encoded bits would decode into a different
// dispatch field than the one set. It decodes the fields that select the
// dispatch field from the encoded bits and repeats the decode selection.
func (e encoder) checkPayload(g *Group, fields []parse.Field) error {
	selectors := dispatchSelectors(e.pdu, fields)
	none := "no payload"
	if fb := fallbackField(e.pdu); fb != nil {
		none = fb.Name
	}
	verb := " select "
	if len(selectors) == 1 {
		verb = " selects "
	}
	sel, err := dispatchSelect(fields, e.pdu, func(field parse.Field) []Code {
		return []Code{Id("_want").Op("=").Lit(field.Name)}
	}, nil)
	if err != nil {
		return err
	}
	g.If(Id("_payload").Op("!=").Lit("")).BlockFunc(func(b *Group) {
		b.Var().Id("result").Id(e.pdu.Name)
		for _, name := range selectors {
			if e.pdu.IsInput(name) {
				b.Id("result").Dot(name).Op("=").Id("s").Dot(name)
				continue
			}
			emitFieldDecode(b, *e.pdu.FieldByName(name), e.pdu)
		}
		b.Id("_want").Op(":=").Lit(none)
		b.Add(sel)
		b.If(Id("_payload").Op("!=").Id("_want")).Block(
			e.fail(Qual("fmt", "Errorf").Call(
				Lit(e.pdu.Name+".%s is set, but "+joinNames(selectors)+verb+"%s"),
				Id("_payload"), Id("_want"),
			)),
		)
	})
	return nil
}

// dispatchSelectors returns the fields that the decode selection of a
// dispatch field reads, in order of first use.
func dispatchSelectors(pdu parse.PDUStruct, fields []parse.Field) []string {
	var names []string
	add := func(name string) {
		for _, n := range names {
			if n == name {
				return
			}
		}
		names = append(names, name)
	}
	add(fields[0].DispatchFieldName)
	if pdu.DispatchIf != nil {
		add(pdu.DispatchIf.Field)
	}
	for _, f := range fields {
		if f.When != nil {
			add(f.When.Field)
		}
	}
	return names
}

func joinNames(names []string) string {
	if len(names) == 1 {
		return names[0]
	}
	return strings.Join(names[:len(names)-1], ", ") + " and " + names[len(names)-1]
}

// dispatch generates a switch that encodes the active dispatch field.
func (e encoder) dispatch(g *Group, fields []parse.Field) {
	bitStart := fields[0].BitStart
	bitEnd := fields[0].BitEnd

	g.Switch().BlockFunc(func(sw *Group) {
		for _, field := range fields {
			sw.Case(Id("s").Dot(field.Name).Op("!=").Nil()).Block(
				List(Id("_pduBits"), Err()).Op(":=").Id("s").Dot(field.Name).Dot("Encode").Call(),
				If(Err().Op("!=").Nil()).Block(
					e.fail(Qual("fmt", "Errorf").Call(Lit(e.pdu.Name+"."+field.Name+": %w"), Err())),
				),
				Copy(Id("data").Index(Lit(bitStart), Lit(bitEnd+1)), Id("_pduBits").Index(Empty(), Empty())),
			)
		}
		if fb := fallbackField(e.pdu); fb != nil {
			sw.Default().BlockFunc(func(d *Group) {
				e.raw(d, *fb)
			})
		}
	})
}

// emitCRCEncode generates CRC calculation and embedding for encoding.
// Supports both byte-level CRC (CRC-CCITT) and bit-level CRC (CRC-8).
func emitCRCEncode(g *Group, pdu parse.PDUStruct, outputSize int) {
	algo := crcAlgorithms[pdu.CRC.Algorithm]
	if algo.BitLevel {
		// Bit-level CRC (e.g. CRC-8): compute over data bits directly
		dataBits := outputSize - algo.CRCBits
		g.Id("_crcVal").Op(":=").Qual(crcPkg, algo.CalcFn).Call(Id("data").Index(Empty(), Lit(dataBits)))
		// Unpack CRC bits (MSB-first)
		g.For(Id("j").Op(":=").Range().Lit(algo.CRCBits)).Block(
			Id("data").Index(Lit(dataBits).Op("+").Id("j")).Op("=").
				Qual(bitPkg, "Bit").Call(
				Parens(Id("_crcVal").Op(">>").Parens(Lit(algo.CRCBits - 1).Op("-").Id("j"))).Op("&").Lit(1),
			),
		)
		return
	}

	// Byte-level CRC (CRC-CCITT)
	totalBytes := outputSize / 8
	dataBytes := totalBytes - 2 // CRC is last 2 bytes

	// Pack the data bits (excluding CRC bytes) into _packedBytes
	g.Var().Id("_encBytes").Index(Lit(dataBytes)).Byte()
	g.For(Id("i").Op(":=").Range().Lit(dataBytes)).Block(
		For(Id("j").Op(":=").Range().Lit(8)).Block(
			Id("_encBytes").Index(Id("i")).Op("<<=").Lit(1),
			Id("_encBytes").Index(Id("i")).Op("|=").Byte().Call(
				Id("data").Index(Id("i").Op("*").Lit(8).Op("+").Id("j")),
			),
		),
	)

	// Calculate CRC
	g.Id("_crcVal").Op(":=").Qual(crcPkg, algo.CalcFn).Call(Id("_encBytes").Index(Empty(), Empty()))

	// CRC bytes (big-endian, swapped like MMDVM: crc8[0]=low, crc8[1]=high)
	g.Id("_crcHigh").Op(":=").Byte().Call(Id("_crcVal").Op(">>").Lit(8))
	g.Id("_crcLow").Op(":=").Byte().Call(Id("_crcVal"))

	// Apply mask if present
	if pdu.CRC != nil && pdu.CRC.HasMask {
		highByte, lowByte := maskBytes(pdu.CRC.Mask)
		g.Id("_crcHigh").Op("^=").Lit(highByte)
		g.Id("_crcLow").Op("^=").Lit(lowByte)
	}

	// Unpack CRC into data bits (last 16 bits)
	crcBitStart := dataBytes * 8
	g.For(Id("j").Op(":=").Range().Lit(8)).Block(
		Id("data").Index(Lit(crcBitStart).Op("+").Id("j")).Op("=").
			Qual(bitPkg, "Bit").Call(
			Parens(Id("_crcHigh").Op(">>").Parens(Lit(7).Op("-").Id("j"))).Op("&").Lit(1),
		),
	)
	g.For(Id("j").Op(":=").Range().Lit(8)).Block(
		Id("data").Index(Lit(crcBitStart+8).Op("+").Id("j")).Op("=").
			Qual(bitPkg, "Bit").Call(
			Parens(Id("_crcLow").Op(">>").Parens(Lit(7).Op("-").Id("j"))).Op("&").Lit(1),
		),
	)
}

// emitPackedFECEncode generates Reed-Solomon encoding for the encode path.
func emitPackedFECEncode(g *Group, enc encoder, codec *FECCodecInfo) error {
	pdu := enc.pdu
	// Pack data bytes (first N data bytes)
	g.Var().Id("_encData").Index(Lit(codec.DataBytes)).Byte()
	g.For(Id("i").Op(":=").Range().Lit(codec.DataBytes)).Block(
		For(Id("j").Op(":=").Range().Lit(8)).Block(
			Id("_encData").Index(Id("i")).Op("<<=").Lit(1),
			Id("_encData").Index(Id("i")).Op("|=").Byte().Call(
				Id("data").Index(Id("i").Op("*").Lit(8).Op("+").Id("j")),
			),
		),
	)

	g.Id("_encoded").Op(":=").Qual(codec.ImportPath, encodeFnName).Call(Id("_encData"))

	var noMask Code
	if pdu.FECMask != nil {
		noMask = enc.fail(Qual("fmt", "Errorf").Call(
			Lit(pdu.Name+"."+pdu.FECMask.Field+": no FEC mask for value %d"), Id("s").Dot(pdu.FECMask.Field)))
	}
	if err := emitFECMask(g, pdu, codec, Id("s"), "_encoded", noMask); err != nil {
		return err
	}

	// Unpack all encoded bytes (data + parity) back into data bits
	totalBytes := enc.size / 8
	g.For(Id("i").Op(":=").Range().Lit(totalBytes)).Block(
		For(Id("j").Op(":=").Range().Lit(8)).Block(
			Id("data").Index(Id("i").Op("*").Lit(8).Op("+").Id("j")).Op("=").
				Qual(bitPkg, "Bit").Call(
				Parens(Id("_encoded").Index(Id("i")).Op(">>").
					Parens(Lit(7).Op("-").Id("j"))).Op("&").Lit(1),
			),
		),
	)
	return nil
}

// field generates the encode logic for a single field.
func (e encoder) field(g *Group, field parse.Field) {
	pdu := e.pdu
	source := Id("s").Dot(field.Name)

	if isIntegerField(field) {
		e.integer(g, field)
		return
	}

	switch field.Kind {
	case parse.FieldUint, parse.FieldInt, parse.FieldEnum:
		// handled by e.integer
	case parse.FieldBool:
		// if s.FieldName { data[bit] = 1 }
		g.If(source.Clone()).Block(
			Id("data").Index(Lit(field.BitStart)).Op("=").Lit(1),
		)

	case parse.FieldRaw:
		e.raw(g, field)

	case parse.FieldPacked:
		g.Copy(
			Id("data").Index(Lit(field.BitStart), Lit(field.BitEnd+1)),
			Qual(bitPkg, "Unpack").Call(source.Clone().Index(Empty(), Empty())),
		)

	case parse.FieldDelegate:
		if field.Stride > 0 {
			// Array delegate with stride: call Encode on each element
			g.For(Id("_i").Op(":=").Lit(0), Id("_i").Op("<").Lit(field.ArrayLen), Id("_i").Op("++")).Block(
				List(Id("_elemBits"), Err()).Op(":=").Add(source.Clone().Index(Id("_i"))).Dot("Encode").Call(),
				If(Err().Op("!=").Nil()).Block(
					e.fail(Qual("fmt", "Errorf").Call(Lit(pdu.Name+"."+field.Name+"[%d]: %w"), Id("_i"), Err())),
				),
				Copy(
					Id("data").Index(
						Lit(field.BitStart).Op("+").Id("_i").Op("*").Lit(field.Stride),
						Lit(field.BitStart).Op("+").Id("_i").Op("*").Lit(field.Stride).Op("+").Lit(field.Stride),
					),
					Id("_elemBits").Index(Empty(), Empty()),
				),
			)
			return
		}
		// Struct delegate: call the generated Encode method
		tmpVar := "_" + strings.ToLower(field.Name[:1]) + field.Name[1:] + "Bits"
		g.List(Id(tmpVar), Err()).Op(":=").Add(source.Clone()).Dot("Encode").Call()
		g.If(Err().Op("!=").Nil()).Block(
			e.fail(Qual("fmt", "Errorf").Call(Lit(pdu.Name+"."+field.Name+": %w"), Err())),
		)
		g.Copy(
			Id("data").Index(Lit(field.BitStart), Lit(field.BitEnd+1)),
			Id(tmpVar).Index(Empty(), Empty()),
		)

	case parse.FieldLongitude, parse.FieldLatitude:
		raw := "_raw" + field.Name
		half := 1 << (field.BitWidth - 1)
		limit := coordSpan(field) / 2
		// Negated form also rejects NaN.
		g.If(Op("!").Parens(source.Clone().Op(">=").Lit(-limit).Op("&&").Add(source.Clone()).Op("<=").Lit(limit))).Block(
			e.failRange(field, Dict{Id("Min"): Lit(-limit), Id("Max"): Lit(limit)}),
		)
		g.Id(raw).Op(":=").Add(coordRaw(field, source.Clone()))
		// +180 degrees longitude rounds to 2^(width-1), which the two's
		// complement store wraps to -180, the same meridian. +90 degrees
		// latitude has no code, so it takes the nearest one.
		if field.Kind == parse.FieldLatitude {
			g.Id(raw).Op("=").Min(Id(raw), Lit(half-1))
		}
		g.Qual(bitPkg, "PutUint").Call(
			Id("data").Index(Lit(field.BitStart), Lit(field.BitEnd+1)),
			Uint64().Call(Int64().Call(Id(raw))),
		)

	case parse.FieldDispatch:
		// Dispatch fields are handled separately in dispatch
	}
}

// raw encodes a raw byte-array field after checking that its padding bits
// are zero.
func (e encoder) raw(g *Group, field parse.Field) {
	n := parse.RawBytes(field.BitWidth)
	if pad := n*8 - field.BitWidth; pad > 0 {
		g.If(Id("s").Dot(field.Name).Index(Lit(n - 1)).Op("&").Lit(1<<pad - 1).Op("!=").Lit(0)).Block(
			e.failRange(field, nil),
		)
	}
	g.For(Id("_i").Op(":=").Range().Lit(field.BitWidth)).Block(
		Id("data").Index(Lit(field.BitStart).Op("+").Id("_i")).Op("=").Qual(bitPkg, "Bit").Call(
			Id("s").Dot(field.Name).Index(Id("_i").Op("/").Lit(8)).Op(">>").Parens(Lit(7).Op("-").Id("_i").Op("%").Lit(8)).Op("&").Lit(1),
		),
	)
}

// packRaw returns a loop that packs the width bits of src from start into
// the byte array dst, most significant bit first. dst starts zero, so its
// padding bits stay zero.
func packRaw(dst, src *Statement, start, width int) *Statement {
	idx := Id("_i")
	if start > 0 {
		idx = Lit(start).Op("+").Id("_i")
	}
	return For(Id("_i").Op(":=").Range().Lit(width)).Block(
		dst.Clone().Index(Id("_i").Op("/").Lit(8)).Op("|=").Byte().Call(src.Clone().Index(idx)).Op("<<").Parens(Lit(7).Op("-").Id("_i").Op("%").Lit(8)),
	)
}

// integer encodes an unsigned, signed, enum or noptr delegate field after
// checking that its value fits the field width.
func (e encoder) integer(g *Group, field parse.Field) {
	source := Id("s").Dot(field.Name)
	w := field.BitWidth
	switch {
	case field.Signed:
		lo, hi := -(1 << (w - 1)), (1<<(w-1))-1
		g.If(Int64().Call(source.Clone()).Op("<").Lit(lo).Op("||").Int64().Call(source.Clone()).Op(">").Lit(hi)).Block(
			e.failRange(field, nil),
		)
	case needsRangeCheck(field):
		g.If(Uint64().Call(source.Clone()).Op(">>").Lit(w).Op("!=").Lit(0)).Block(
			e.failRange(field, nil),
		)
	}

	value := source.Clone()
	if field.GoType != typUint64 {
		value = Uint64().Call(value)
	}
	storeBits(g, field.Ranges(), value, "_val"+field.Name)
}

// constant encodes a dmr:const directive.
func (e encoder) constant(g *Group, c parse.ConstDirective, idx int) {
	var value *Statement
	if n, err := strconv.ParseUint(c.Value, 0, 64); err == nil {
		value = Uint64().Call(Id(strconv.FormatUint(n, 10)))
	} else {
		value = Uint64().Call(emitDispatchConstant(c.Value, e.pdu))
	}
	storeBits(g, c.Ranges, value, fmt.Sprintf("_const%d", idx))
}

// storeBits stores the uint64 value MSB-first across ranges. A
// non-contiguous value goes through the temporary variable tmp.
func storeBits(g *Group, ranges [][2]int, value *Statement, tmp string) {
	if len(ranges) == 1 {
		g.Qual(bitPkg, "PutUint").Call(Id("data").Index(Lit(ranges[0][0]), Lit(ranges[0][1]+1)), value)
		return
	}

	g.Id(tmp).Op(":=").Add(value)
	remaining := 0
	for _, r := range ranges {
		remaining += r[1] - r[0] + 1
	}
	for _, r := range ranges {
		remaining -= r[1] - r[0] + 1
		seg := Id(tmp)
		if remaining > 0 {
			seg = Id(tmp).Op(">>").Lit(remaining)
		}
		g.Qual(bitPkg, "PutUint").Call(Id("data").Index(Lit(r[0]), Lit(r[1]+1)), seg)
	}
}

// isIntegerField reports whether a field is stored as a plain integer value.
func isIntegerField(field parse.Field) bool {
	switch field.Kind {
	case parse.FieldUint, parse.FieldInt, parse.FieldEnum:
		return true
	case parse.FieldDelegate:
		return field.DelegateNoPtr && field.Stride == 0
	case parse.FieldBool, parse.FieldRaw, parse.FieldPacked, parse.FieldLongitude, parse.FieldLatitude, parse.FieldDispatch:
	}
	return false
}

// needsRangeCheck reports whether an unsigned field's Go type can hold values
// wider than the field.
func needsRangeCheck(field parse.Field) bool {
	switch field.BaseType {
	case typUint8, "byte":
		return field.BitWidth < 8
	case typUint16:
		return field.BitWidth < 16
	case typUint32:
		return field.BitWidth < 32
	}
	return true
}

// emitNonContiguousDecode generates decode logic for a non-contiguous uint field.
// For example, bits:3+12-15 means bit 3 is the MSB and bits 12-15 are the lower nibble.
// It accumulates segments in a temp variable: extract first range, shift left, OR next range, etc.
func emitNonContiguousDecode(g *Group, field parse.Field, pdu parse.PDUStruct) {
	tmpName := "_tmp" + field.Name
	g.Var().Id(tmpName).Uint64()
	for i, r := range field.Ranges() {
		read := Qual(bitPkg, "Uint").Call(Id("data").Index(Lit(r[0]), Lit(r[1]+1)))
		if i == 0 {
			g.Id(tmpName).Op("=").Add(read)
			continue
		}
		g.Id(tmpName).Op("<<=").Lit(r[1] - r[0] + 1)
		g.Id(tmpName).Op("|=").Add(read)
	}

	target := Id("result").Dot(field.Name)
	tmp := Id(tmpName)
	if field.Signed {
		g.Add(target).Op("=").Add(qualType(field, pdu)).Call(signExtend(field, Uint32().Call(tmp)))
		return
	}
	g.Add(target).Op("=").Add(castUint(field, pdu, tmp))
}

// Helper functions

// maskBytes splits a 16-bit CRC mask into its high and low bytes.
func maskBytes(mask uint16) (byte, byte) {
	var b [2]byte
	binary.BigEndian.PutUint16(b[:], mask)
	return b[0], b[1]
}

// readUint reads a contiguous field as a uint64.
func readUint(field parse.Field) *Statement {
	return Qual(bitPkg, "Uint").Call(Id("data").Index(Lit(field.BitStart), Lit(field.BitEnd+1)))
}

// castUint converts the uint64 expression v to the type of field.
func castUint(field parse.Field, pdu parse.PDUStruct, v *Statement) *Statement {
	if field.GoType == typUint64 {
		return v
	}
	return qualType(field, pdu).Call(v)
}

// signExtend converts a width-bit two's complement value held in a uint32
// expression to int32.
func signExtend(field parse.Field, raw *Statement) *Statement {
	shift := 32 - field.BitWidth
	if shift == 0 {
		return Int32().Call(raw)
	}
	return Int32().Call(raw.Op("<<").Lit(shift)).Op(">>").Lit(shift)
}

// coordSpan returns the full range in degrees of a latitude or longitude field.
func coordSpan(field parse.Field) float64 {
	if field.Kind == parse.FieldLongitude {
		return 360
	}
	return 180
}

// coordRaw converts a coordinate in degrees to the nearest raw step count.
func coordRaw(field parse.Field, value *Statement) *Statement {
	return Qual("math", "Round").Call(
		value.Op("*").Parens(Lit(1).Op("<<").Lit(field.BitWidth)).Op("/").Lit(coordSpan(field)),
	)
}

// inputParamName converts a dmr:input field name to its Decode parameter name.
func inputParamName(field string) string {
	name := strings.ToLower(field[:1]) + field[1:]
	switch name {
	case "data", "result", "corrected":
		return "_" + name
	}
	return name
}

func qualType(field parse.Field, pdu parse.PDUStruct) *Statement {
	if field.IsQualified {
		importPath := resolveImportPath(field.TypePkg, pdu.SourceFile)
		return Qual(importPath, field.TypeName)
	}
	return Id(field.GoType)
}

// isFixedArray returns true if the Go type is a fixed-size array (e.g. "[12]byte")
// as opposed to a slice (e.g. "[]byte").
func isFixedArray(goType string) bool {
	return strings.HasPrefix(goType, "[") && !strings.HasPrefix(goType, "[]")
}
