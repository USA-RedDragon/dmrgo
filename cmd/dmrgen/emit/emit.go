// resolveImportPath converts a short package name (e.g. "enums") to a full import path.
func resolveImportPath(pkgName, sourceFile string) string {
	knownPkgs := map[string]string{
		"enums":            "github.com/USA-RedDragon/dmrgo/v2/enums",
		"bit":              "github.com/USA-RedDragon/dmrgo/v2/bit",
		"fec":              "github.com/USA-RedDragon/dmrgo/v2/fec",
		"layer3":           "github.com/USA-RedDragon/dmrgo/v2/layer3",
		"golay":            "github.com/USA-RedDragon/dmrgo/v2/internal/fec/golay",
		"quadraticResidue": qrPkg,
		"reedSolomon":      "github.com/USA-RedDragon/dmrgo/v2/internal/fec/reedsolomon",
		"bptc":             "github.com/USA-RedDragon/dmrgo/v2/internal/fec/bptc",
		"trellis":          "github.com/USA-RedDragon/dmrgo/v2/internal/fec/trellis",
		"hamming":          "github.com/USA-RedDragon/dmrgo/v2/internal/fec/hamming",
		"vocoder":          "github.com/USA-RedDragon/dmrgo/v2/vocoder",
	}
	if p, ok := knownPkgs[pkgName]; ok {
		return p
	}
	dir := filepath.Dir(sourceFile)
	return "github.com/USA-RedDragon/dmrgo/" + filepath.Join(dir, pkgName)
}

// GenerateFile produces the _decode_gen.go content for a set of PDU structs.
func GenerateFile(pdus []parse.PDUStruct, pkgName string) (*File, error) {
	f := NewFile(pkgName)

	f.HeaderComment("Code generated by dmrgen. DO NOT EDIT.")
	seen := map[string]bool{}
	for _, pdu := range pdus {
		if pdu.SpecRef != "" && !seen[pdu.SpecRef] {
			if len(seen) == 0 {
				f.HeaderComment("//")
			}
			f.HeaderComment(pdu.SpecRef)
			seen[pdu.SpecRef] = true
		}
	}

	ev := &errVars{defs: map[string]Code{}}
	for _, pdu := range pdus {
		if err := emitDecode(f, pdu, false); err != nil {
			return nil, fmt.Errorf("generating decode for %s: %w", pdu.Name, err)
		}
		f.Line()
		if payloads := dispatchPayloads(pdu); len(payloads) > 0 {
			emitPayloads(f, pdu, payloads)
			f.Line()
			if err := emitDecode(f, pdu, true); err != nil {
				return nil, fmt.Errorf("generating decode for %s: %w", pdu.Name, err)
			}
			f.Line()
		}
		if err := emitEncode(f, pdu, ev); err != nil {
			return nil, fmt.Errorf("generating encode for %s: %w", pdu.Name, err)
		}
		f.Line()
		emitString(f, pdu)
	}
	if len(ev.names) > 0 {
		f.Line()
		f.Comment("The errors of the Encode methods. Each is a static value, so that an")
		f.Comment("Encode that fails does not allocate.")
		f.Var().DefsFunc(func(g *Group) {
			for _, name := range ev.names {
				g.Id(name).Op("=").Add(ev.defs[name])
			}
		})
	}

	return f, nil
}

// errVars collects the package-level error values that the Encode methods
// of a file return, in the order of first use.
type errVars struct {
	names []string
	defs  map[string]Code
}

// get returns the variable name for an error value, declaring it with def
// on first use.
func (v *errVars) get(name string, def Code) Code {
	if _, ok := v.defs[name]; !ok {
		v.names = append(v.names, name)
		v.defs[name] = def
	}
	return Id(name)
}

// errorsNew returns errors.New(text).
func errorsNew(text string) Code {
	return Qual("errors", "New").Call(Lit(text))
}

// docObject returns the object of a generated doc sentence: the struct name
// with its article, the citation in parentheses and a final period.
func docObject(pdu parse.PDUStruct) string {
	s := article(pdu.Name) + " " + pdu.Name
	if pdu.SpecRef != "" {
		s += " (" + pdu.SpecRef + ")"
	}
	return s + "."
}

// article returns "an" when name is read with a leading vowel sound, else
// "a". An acronym such as MBC or FLC is read by its letter names.
func article(name string) string {
	if name == "" {
		return "a"
	}
	first := name[0]
	if len(name) > 1 && name[1] >= 'A' && name[1] <= 'Z' {
		if strings.IndexByte("AEFHILMNORSX", first) >= 0 {
			return "an"
		}
		return "a"
	}
	if strings.IndexByte("AEIO", first) >= 0 {
		return "an"
	}
	if first == 'U' && !strings.HasPrefix(name, "Uni") {
		return "an"
	}
	return "a"
}

// emitDecode generates the packed decode function of a PDU struct,
// decodeXxxBytes, and, unless the struct is a sub-PDU, its exported form
// DecodeXxx, which takes bit.Bit values. With into, it generates
// decodeXxxBytesInto and DecodeXxxInto, which decode into a caller's struct
// and point the dispatch field into a caller's payloads struct.
func emitDecode(f *File, pdu parse.PDUStruct, into bool) error {
	codec, hasFEC, err := resolveCodec(pdu)
	if err != nil {
		return err
	}
	inputSize := pdu.InputSize
	if hasFEC {
		inputSize = codec.InputSize
	}
	if err := emitDecodeBytes(f, pdu, into, codec, inputSize); err != nil {
		return err
	}
	if !pdu.UnexportedDecode[pdu.Name] {
		f.Line()
		emitDecodeAdapter(f, pdu, into, inputSize)
	}
	return nil
}

// bytesDecodeName returns the name of the packed decode function of the
// struct typeName.
func bytesDecodeName(typeName string, into bool) string {
	name := "decode" + typeName + "Bytes"
	if into {
		name += "Into"
	}
	return name
}

// ownDecodeName returns the name of the packed decode function of pdu. The
// function of a PDU with dispatch fields that is not the Into form
// allocates the payload struct, so it is named as a constructor.
func ownDecodeName(pdu parse.PDUStruct, into bool) string {
	if !into && len(dispatchPayloads(pdu)) > 0 {
		return "new" + pdu.Name + "Bytes"
	}
	return bytesDecodeName(pdu.Name, into)
}

// emitDecodeAdapter generates DecodeXxx (or DecodeXxxInto), which packs its
// bit.Bit values and calls the packed decode function.
func emitDecodeAdapter(f *File, pdu parse.PDUStruct, into bool, inputSize int) {
	funcName := pdu.DecodeFuncName(pdu.Name)
	if into {
		f.Comment(funcName + "Into decodes data into dst as " + funcName + " does,")
		f.Comment("but points the dispatch field of dst into p, so it does not allocate.")
		f.Comment("The payload stays valid until the next decode into p. dst and p must")
		f.Comment("not be nil.")
	} else {
		f.Comment(funcName + " decodes " + docObject(pdu))
		if len(dispatchPayloads(pdu)) > 0 {
			f.Comment("It allocates the payload struct that the dispatch field points to;")
			f.Comment(funcName + "Into does not.")
		}
	}
	var params, args []Code
	if into {
		params = append(params, Id("dst").Op("*").Id(pdu.Name), Id("p").Op("*").Id(payloadsTypeName(pdu)))
		args = append(args, Id("dst"), Id("p"))
	}
	params = append(params, Id("data").Index(Lit(inputSize)).Qual(bitPkg, "Bit"))
	args = append(args, Id("_b"))
	for _, in := range pdu.Inputs {
		params = append(params, Id(inputParamName(in)).Add(qualType(*pdu.FieldByName(in), pdu)))
		args = append(args, Id(inputParamName(in)))
	}
	body := []Code{
		Var().Id("_b").Index(Lit(packedSize(inputSize))).Byte(),
		For(Id("_i").Op(":=").Range().Lit(inputSize)).Block(
			Id("_b").Index(Id("_i").Op("/").Lit(8)).Op("|=").Byte().Call(Id("data").Index(Id("_i")).Op("&").Lit(1)).
				Op("<<").Parens(Lit(7).Op("-").Id("_i").Op("%").Lit(8)),
		),
	}
	call := Id(ownDecodeName(pdu, into)).Call(args...)
	if into {
		f.Func().Id(funcName + "Into").Params(params...).Block(append(body, call)...)
		return
	}
	f.Func().Id(funcName).Params(params...).Id(pdu.Name).Block(append(body, Return(call))...)
}

// emitDecodeBytes generates the packed decode function of a PDU struct,
// which reads data, the inputSize bits of the PDU packed most significant
// bit first.
func emitDecodeBytes(f *File, pdu parse.PDUStruct, into bool, codec *FECCodecInfo, inputSize int) error {
	name := ownDecodeName(pdu, into)
	if into {
		f.Comment(name + " decodes " + docObject(pdu))
		f.Comment("data holds its bits packed, the first bit most significant. It decodes")
		f.Comment("into dst and points the dispatch field of dst into p.")
	} else {
		f.Comment(name + " decodes " + docObject(pdu))
		f.Comment("data holds its bits packed, the first bit most significant.")
		if len(dispatchPayloads(pdu)) > 0 {
			f.Comment("It allocates the payload struct that the dispatch field points to.")
		}
	}

	var params []Code
	if into {
		params = append(params, Id("dst").Op("*").Id(pdu.Name), Id("p").Op("*").Id(payloadsTypeName(pdu)))
	}
	params = append(params, Id("data").Index(Lit(packedSize(inputSize))).Byte())
	for _, in := range pdu.Inputs {
		field := pdu.FieldByName(in)
		if field == nil {
			return fmt.Errorf("dmr:input %q is not a field", in)
		}
		params = append(params, Id(inputParamName(in)).Add(qualType(*field, pdu)))
	}

	var fn *Statement
	if into {
		fn = f.Func().Id(name).Params(params...)
	} else {
		fn = f.Func().Id(name).Params(params...).Id(pdu.Name)
	}
	var genErr error
	fn.BlockFunc(func(g *Group) {
		if into {
			g.Op("*").Id("dst").Op("=").Id(pdu.Name).Values()
			g.Id("result").Op(":=").Id("dst")
		} else {
			g.Var().Id("result").Id(pdu.Name)
		}
		for _, in := range pdu.Inputs {
			g.Id("result").Dot(in).Op("=").Id(inputParamName(in))
		}

		switch {
		case pdu.CRC != nil:
			if err := emitCRCCheck(g, pdu, inputSize); err != nil {
				genErr = err
				return
			}
		case codec != nil && codec.PackedBytes:
			g.Id("_cw").Op(":=").Id("data")
			if err := emitFECMask(g, pdu, codec, Id("result"), "_cw", nil); err != nil {
				genErr = err
				return
			}
			g.Var().Id("_fecData").Index(Lit(codec.DataBytes)).Byte()
			g.List(Id("_fecData"), Id("result").Dot(fecFieldName)).Op("=").Qual(codec.ImportPath, codec.DecodeFn).Call(Id("_cw"))
			g.If(Op("!").Id("result").Dot(fecFieldName).Dot("Uncorrectable")).Block(
				Copy(Id("data").Index(Empty(), Lit(codec.DataBytes)), Id("_fecData").Index(Empty(), Empty())),
			)
		case codec != nil:
			g.Var().Id("_cw").Id(codec.WordType)
			g.List(Id("_cw"), Id("result").Dot(fecFieldName)).Op("=").Qual(codec.ImportPath, codec.DecodeFn).Call(
				Id(codec.WordType).Call(readPacked(dataBuf, 0, codec.InputSize)))
			g.If(Op("!").Id("result").Dot(fecFieldName).Dot("Uncorrectable")).Block(
				writePacked(dataBuf, 0, codec.InputSize, Uint64().Call(Id("_cw")), "_cwBits")...,
			)
		}

		var dispatchFields []parse.Field
		for _, field := range pdu.Fields {
			if field.Skip {
				continue
			}
			if field.Kind == parse.FieldDispatch {
				dispatchFields = append(dispatchFields, field)
				continue
			}
			if field.Fallback {
				continue
			}
			emitFieldDecode(g, field, pdu)
		}

		if len(dispatchFields) > 0 {
			if err := emitDispatchSwitch(g, dispatchFields, pdu, into); err != nil {
				genErr = err
				return
			}
		}

		if !into {
			g.Return(Id("result"))
		}
	})
	return genErr
}

// packedSize returns the number of bytes that hold n bits.
func packedSize(n int) int {
	return (n + 7) / 8
}

// dataBuf returns the data identifier, the packed bits of a decode or
// encode function.
func dataBuf() *Statement {
	return Id("data")
}

// hexByte returns a byte literal in hexadecimal.
func hexByte(b byte) *Statement {
	return Id(fmt.Sprintf("0x%02X", b))
}

// readPacked returns a uint64 expression of the n bits of the packed byte
// array buf from bit start, the first bit most significant.
func readPacked(buf func() *Statement, start, n int) *Statement {
	first, last := start/8, (start+n-1)/8
	if last-first >= 8 {
		hi := n - 32
		return Parens(readPacked(buf, start, hi).Op("<<").Lit(32).Op("|").Add(readPacked(buf, start+hi, 32)))
	}
	shift := 7 - (start+n-1)%8
	var e *Statement
	for k := first; k <= last; k++ {
		term := Uint64().Call(buf().Index(Lit(k)))
		if sh := 8 * (last - k); sh > 0 {
			term = term.Op("<<").Lit(sh)
		}
		if e == nil {
			e = term
		} else {
			e = e.Op("|").Add(term)
		}
	}
	if first != last && (shift > 0 || start%8 != 0) {
		e = Parens(e)
	}
	if shift > 0 {
		e = e.Op(">>").Lit(shift)
	}
	if start%8 != 0 {
		e = e.Op("&").Id(fmt.Sprintf("0x%X", uint64(1)<<n-1))
	}
	return e
}

// writePacked returns statements that store the low n bits of the uint64
// expression v into the packed byte array buf from bit start and keep the
// other bits of buf. A v that spans bytes is first stored in tmp, unless tmp
// is "".
func writePacked(buf func() *Statement, start, n int, v *Statement, tmp string) []Code {
	first, last := start/8, (start+n-1)/8
	var out []Code
	val := v
	if first != last && tmp != "" {
		out = append(out, Id(tmp).Op(":=").Add(v))
		val = Id(tmp)
	}
	for k := first; k <= last; k++ {
		sh := start + n - 1 - (8*k + 7)
		var b *Statement
		switch {
		case sh > 0:
			b = Byte().Call(val.Clone().Op(">>").Lit(sh))
		case sh < 0:
			b = Byte().Call(val.Clone().Op("<<").Lit(-sh))
		default:
			b = Byte().Call(val.Clone())
		}
		var m byte
		for p := max(start, 8*k); p <= min(start+n-1, 8*k+7); p++ {
			m |= 0x80 >> (p - 8*k)
		}
		if m == 0xFF {
			out = append(out, buf().Index(Lit(k)).Op("=").Add(b))
			continue
		}
		out = append(out, buf().Index(Lit(k)).Op("=").Add(buf().Index(Lit(k))).Op("&^").Add(hexByte(m)).
			Op("|").Add(b).Op("&").Add(hexByte(m)))
	}
	return out
}

// copyBits returns statements that copy n bits of the packed byte array src
// from bit srcStart to dst from bit dstStart and keep the other bits of dst.
func copyBits(dst func() *Statement, dstStart int, src func() *Statement, srcStart, n int) []Code {
	if dstStart%8 != 0 || srcStart%8 != 0 {
		return []Code{Qual(bitsPkg, "Copy").Call(dst().Index(Empty(), Empty()), Lit(dstStart), src().Index(Empty(), Empty()), Lit(srcStart), Lit(n))}
	}
	a, b, full, rem := dstStart/8, srcStart/8, n/8, n%8
	var out []Code
	switch {
	case full == 1:
		out = append(out, dst().Index(Lit(a)).Op("=").Add(src().Index(Lit(b))))
	case full > 1:
		out = append(out, Copy(dst().Index(Lit(a), Lit(a+full)), src().Index(Lit(b), Lit(b+full))))
	}
	if rem > 0 {
		m := byte(0xFF) << (8 - rem)
		out = append(out, dst().Index(Lit(a+full)).Op("=").Add(dst().Index(Lit(a+full))).Op("&^").Add(hexByte(m)).
			Op("|").Add(src().Index(Lit(b+full))).Op("&").Add(hexByte(m)))
	}
	return out
}

// addAll adds each statement of codes to g.
func addAll(g *Group, codes []Code) {
	for _, c := range codes {
		g.Add(c)
	}
}

// fieldOf returns a function that returns the expression x.name, such as
// result.Data, for copyBits.
func fieldOf(x, name string) func() *Statement {
	return func() *Statement { return Id(x).Dot(name) }
}

// idOf returns a function that returns the identifier name, for copyBits.
func idOf(name string) func() *Statement {
	return func() *Statement { return Id(name) }
}

// resolveCodec looks up the FEC codec and CRC algorithm of a PDU and checks
// that its fields fit the codec's data bits. ok is false for a PDU without a
// dmr:fec directive.
func resolveCodec(pdu parse.PDUStruct) (codec *FECCodecInfo, ok bool, err error) {
	if pdu.CRC != nil {
		if _, found := crcAlgorithms[pdu.CRC.Algorithm]; !found {
			return nil, false, fmt.Errorf("unknown CRC algorithm: %q", pdu.CRC.Algorithm)
		}
	}
	if pdu.FEC == nil {
		return nil, false, nil
	}
	c, found := fecCodecs[pdu.FEC.Codec]
	if !found {
		return nil, false, fmt.Errorf("unknown FEC codec: %s", pdu.FEC.Codec)
	}
	if pdu.CRC != nil {
		return nil, false, errors.New("dmr:fec and dmr:crc cannot be combined")
	}
	dataBits := c.DataBits
	if c.PackedBytes {
		dataBits = c.DataBytes * 8
	}
	if pdu.InputSize > dataBits {
		return nil, false, fmt.Errorf("fields span %d bits but %s carries %d data bits", pdu.InputSize, pdu.FEC.Codec, dataBits)
	}
	return &c, true, nil
}

// emitCRCCheck generates the CRC check of the packed bits data, for a
// byte-level CRC (CRC-CCITT) or a bit-level CRC (CRC-8).
func emitCRCCheck(g *Group, pdu parse.PDUStruct, inputSize int) error {
	crcDir := pdu.CRC

	algo, ok := crcAlgorithms[crcDir.Algorithm]
	if !ok {
		return fmt.Errorf("unknown CRC algorithm: %q", crcDir.Algorithm)
	}
	if algo.BitLevel {
		dataBits := inputSize - algo.CRCBits
		g.Id("result").Dot(fecFieldName).Dot("Uncorrectable").Op("=").
			Op("!").Qual(crcPkg, algo.CheckFn).Call(Id("data").Index(Empty(), Empty()), Lit(dataBits),
			Uint8().Call(readPacked(dataBuf, dataBits, algo.CRCBits)))
		return nil
	}

	totalBytes := inputSize / 8
	want := Uint16().Call(Id("data").Index(Lit(totalBytes - 2))).Op("<<").Lit(8).
		Op("|").Uint16().Call(Id("data").Index(Lit(totalBytes - 1)))
	if crcDir.HasMask {
		want = Parens(want).Op("^").Id(fmt.Sprintf("0x%04X", crcDir.Mask))
	}
	g.Id("result").Dot(fecFieldName).Dot("Uncorrectable").Op("=").
		Op("!").Qual(crcPkg, algo.CheckFn).Call(Id("data").Index(Empty(), Lit(totalBytes-2)), want)
	return nil
}

// emitFECMask XORs the FEC parity bytes of buf with the mask selected by the
// dmr:fec_mask field of src (ETSI TS 102 361-1 clause B.3.12, Table B.21). If
// noMask is not nil, it is emitted for a field value with no mask.
func emitFECMask(g *Group, pdu parse.PDUStruct, codec *FECCodecInfo, src *Statement, buf string, noMask Code) error {
	if pdu.FECMask == nil {
		return nil
	}
	if !codec.PackedBytes {
		return fmt.Errorf("dmr:fec_mask is only supported for packed-byte codecs, not %s", pdu.FEC.Codec)
	}
	parityBytes := codec.TotalBytes - codec.DataBytes
	var genErr error
	g.Switch(src.Clone().Dot(pdu.FECMask.Field)).BlockFunc(func(sw *Group) {
		for _, m := range pdu.FECMask.Masks {
			if m.Mask>>(8*parityBytes) != 0 {
				genErr = fmt.Errorf("dmr:fec_mask %#x is wider than %d parity bytes", m.Mask, parityBytes)
				return
			}
			var stmts []Code
			for k := range parityBytes {
				b := (m.Mask >> (8 * (parityBytes - 1 - k))) & 0xFF
				stmts = append(stmts, Id(buf).Index(Lit(codec.DataBytes+k)).Op("^=").Id(fmt.Sprintf("0x%02X", b)))
			}
			sw.Case(emitDispatchConstant(m.Value, pdu)).Block(stmts...)
		}
		if noMask != nil {
			sw.Default().Block(noMask)
		}
	})
	return genErr
}

// emitDispatchSwitch emits a switch on the dispatch field value that decodes
// the selected sub-PDU into its pointer field. A when: guard picks between
// fields that share a dispatch value. With into, the sub-PDU is decoded into
// its field of the payloads struct p.
func emitDispatchSwitch(g *Group, fields []parse.Field, pdu parse.PDUStruct, into bool) error {
	bitStart := fields[0].BitStart
	n := fields[0].BitEnd - bitStart + 1

	tmpVar := "_dispatchBytes"
	g.Var().Id(tmpVar).Index(Lit(packedSize(n))).Byte()
	addAll(g, copyBits(idOf(tmpVar), 0, dataBuf, bitStart, n))

	var raw []Code
	if fb := fallbackField(pdu); fb != nil {
		raw = copyBits(fieldOf("result", fb.Name), 0, dataBuf, bitStart, fb.BitWidth)
	}
	stmt, err := dispatchSelect(fields, pdu, func(field parse.Field) []Code {
		return dispatchDecodeBlock(field, tmpVar, into)
	}, raw)
	if err != nil {
		return err
	}
	g.Add(stmt)
	return nil
}

// dispatchSelect builds the statement that selects a dispatch field from the
// decoded fields of result. It emits pick for the selected field and raw
// (if not nil) when no field is selected.
func dispatchSelect(fields []parse.Field, pdu parse.PDUStruct, pick func(parse.Field) []Code, raw []Code) (*Statement, error) {
	type dispatchGroup struct {
		values []string
		fields []parse.Field
	}
	var groups []dispatchGroup
	groupIndex := map[string]int{}
	for _, field := range fields {
		key := strings.Join(field.DispatchValues, "|")
		if idx, ok := groupIndex[key]; ok {
			groups[idx].fields = append(groups[idx].fields, field)
		} else {
			groupIndex[key] = len(groups)
			groups = append(groups, dispatchGroup{values: field.DispatchValues, fields: []parse.Field{field}})
		}
	}

	var genErr error
	sw := Switch(Id("result").Dot(fields[0].DispatchFieldName)).BlockFunc(func(sw *Group) {
		for _, grp := range groups {
			caseValues := make([]Code, len(grp.values))
			for i, val := range grp.values {
				caseValues[i] = emitDispatchConstant(val, pdu)
			}

			if len(grp.fields) == 1 && grp.fields[0].When == nil {
				sw.Case(caseValues...).Block(pick(grp.fields[0])...)
				continue
			}
			sw.Case(caseValues...).BlockFunc(func(caseBody *Group) {
				if err := emitGuardedDispatch(caseBody, grp.fields, pick, raw); err != nil && genErr == nil {
					genErr = err
				}
			})
		}
		if raw != nil {
			sw.Default().Block(raw...)
		}
	})
	if genErr != nil {
		return nil, genErr
	}

	if pdu.DispatchIf == nil {
		return sw, nil
	}
	cond, err := emitGuardCondition(pdu.DispatchIf)
	if err != nil {
		return nil, fmt.Errorf("dmr:dispatch_if: %w", err)
	}
	stmt := If(cond).Block(sw)
	if raw != nil {
		stmt.Else().Block(raw...)
	}
	return stmt, nil
}

// fallbackField returns the raw field that holds undispatched payloads, or nil.
func fallbackField(pdu parse.PDUStruct) *parse.Field {
	for i := range pdu.Fields {
		if pdu.Fields[i].Fallback {
			return &pdu.Fields[i]
		}
	}
	return nil
}

// dispatchDecodeBlock decodes the sub-PDU of field from tmpVar and points
// the field to it: to a new value, or with into to its field of p.
func dispatchDecodeBlock(field parse.Field, tmpVar string, into bool) []Code {
	typ := dispatchTypeName(field)
	decode := Id(bytesDecodeName(typ, false)).Call(Id(tmpVar))
	if into {
		slot := Id("p").Dot(payloadFieldName(typ))
		return []Code{
			slot.Clone().Op("=").Add(decode),
			Id("result").Dot(field.Name).Op("=").Op("&").Add(slot.Clone()),
		}
	}
	return []Code{
		Id("_decoded").Op(":=").Add(decode),
		Id("result").Dot(field.Name).Op("=").Op("&").Id("_decoded"),
	}
}

// dispatchPayloads returns the distinct types that the dispatch fields of
// pdu point to, in field order.
func dispatchPayloads(pdu parse.PDUStruct) []string {
	var types []string
	for _, field := range pdu.Fields {
		if field.Skip || field.Kind != parse.FieldDispatch {
			continue
		}
		if typ := dispatchTypeName(field); !slices.Contains(types, typ) {
			types = append(types, typ)
		}
	}
	return types
}

// payloadsTypeName returns the name of the payloads struct of pdu.
func payloadsTypeName(pdu parse.PDUStruct) string {
	return pdu.Name + "Payloads"
}

// payloadFieldName returns the unexported field name of the payloads struct
// for the type typ: the leading capitals in lower case, except the capital
// that starts the next word, as "BSOutboundActivationPDU" gives
// "bsOutboundActivationPDU".
func payloadFieldName(typ string) string {
	n := 0
	for n < len(typ) && typ[n] >= 'A' && typ[n] <= 'Z' {
		n++
	}
	if n > 1 && n < len(typ) {
		n--
	}
	name := strings.ToLower(typ[:n]) + typ[n:]
	if token.IsKeyword(name) {
		name += "_"
	}
	return name
}

// emitPayloads generates the payloads struct of pdu, with one field of each
// type in types, for DecodeXxxInto.
func emitPayloads(f *File, pdu parse.PDUStruct, types []string) {
	name := payloadsTypeName(pdu)
	f.Comment(name + " holds one payload struct of each type that")
	f.Comment(article(pdu.Name) + " " + pdu.Name + " dispatch field points to, for Decode" + pdu.Name + "Into.")
	f.Comment("The zero value is ready to use.")
	f.Type().Id(name).StructFunc(func(g *Group) {
		for _, typ := range types {
			g.Id(payloadFieldName(typ)).Id(typ)
		}
	})
}

func dispatchTypeName(field parse.Field) string {
	if field.IsPointer && field.PointedType != "" {
		return field.PointedType
	}
	return field.TypeName
}

// emitGuardedDispatch emits an if/else chain on the when: guards of fields
// that share a dispatch value. The unguarded field, or else raw if not nil,
// is the final else branch.
func emitGuardedDispatch(g *Group, fields []parse.Field, pick func(parse.Field) []Code, raw []Code) error {
	var guarded []parse.Field
	var fallback *parse.Field
	for i := range fields {
		if fields[i].When != nil {
			guarded = append(guarded, fields[i])
			continue
		}
		if fallback != nil {
			return fmt.Errorf("dispatch fields %s and %s share values and neither has a when: guard", fallback.Name, fields[i].Name)
		}
		fb := fields[i]
		fallback = &fb
	}

	// Build the guard chain as a single jennifer *Statement so that
	// "} else {" stays on one line.
	var chain *Statement
	for i, field := range guarded {
		guardCond, err := emitGuardCondition(field.When)
		if err != nil {
			return fmt.Errorf("field %s: %w", field.Name, err)
		}
		if i == 0 {
			chain = If(guardCond).Block(pick(field)...)
		} else {
			chain.Else().If(guardCond).Block(pick(field)...)
		}
	}
	switch {
	case fallback != nil:
		chain.Else().Block(pick(*fallback)...)
	case raw != nil:
		chain.Else().Block(raw...)
	}
	g.Add(chain)
	return nil
}

// emitGuardCondition generates the Code for a guard condition on the decoded result,
// e.g. result.AppendedBlocks == 0 or result.TrunkingMode == true.
func emitGuardCondition(guard *parse.Guard) (*Statement, error) {
	lhs := Id("result").Dot(guard.Field)

	var val *Statement
	switch guard.Value {
	case "true", "false":
		if (guard.Value == "true") == (guard.Op == "==") {
			return lhs, nil
		}
		return Op("!").Add(lhs), nil
	default:
		n, err := strconv.Atoi(guard.Value)
		if err != nil {
			return nil, fmt.Errorf("guard value %q is not an integer or bool", guard.Value)
		}
		val = Lit(n)
	}

	switch guard.Op {
	case "==", "!=":
		return lhs.Op(guard.Op).Add(val), nil
	default:
		return nil, fmt.Errorf("unsupported guard operator %q", guard.Op)
	}
}

// emitDispatchConstant returns a reference to the dispatch constant val. A
// val with a "." names a constant of another package, such as
// "enums.FLCOGroupVoiceChannelUser".
func emitDispatchConstant(val string, pdu parse.PDUStruct) Code {
	if idx := strings.LastIndex(val, "."); idx >= 0 {
		pkg := val[:idx]
		name := val[idx+1:]
		importPath := resolveImportPath(pkg, pdu.SourceFile)
		return Qual(importPath, name)
	}
	return Id(val)
}

// emitString generates the String method of a PDU struct: one fmt.Sprintf,
// or string concatenation when the struct has dispatch or stride fields.
func emitString(f *File, pdu parse.PDUStruct) {
	hasDispatch := false
	hasStride := false
	for _, field := range pdu.Fields {
		if field.Skip {
			continue
		}
		if field.Kind == parse.FieldDispatch {
			hasDispatch = true
		}
		if field.Stride > 0 && field.ArrayLen > 0 {
			hasStride = true
		}
	}

	if hasDispatch || hasStride {
		emitStringConcat(f, pdu)
	} else {
		emitStringSprintf(f, pdu)
	}
}

// emitStringSprintf generates a String method using a single fmt.Sprintf call.
func emitStringSprintf(f *File, pdu parse.PDUStruct) {
	var formatParts []string
	var args []Code

	for _, field := range pdu.Fields {
		fmtToken, fmtArgs := toStringFieldFormat(field, pdu)
		if fmtToken == "" {
			continue
		}
		formatParts = append(formatParts, field.Name+": "+fmtToken)
		args = append(args, fmtArgs...)
	}

	formatStr := pdu.Name + "{ " + strings.Join(formatParts, ", ") + " }"
	allArgs := append([]Code{Lit(formatStr)}, args...)

	f.Comment("String returns the fields of s as text, for printing. It allocates the")
	f.Comment("string.")
	f.Func().Params(Id("s").Op("*").Id(pdu.Name)).Id("String").Params().String().Block(
		Return(Qual("fmt", "Sprintf").Call(allArgs...)),
	)
}

// emitStringConcat generates a String method using string concatenation for dispatch/stride fields.
func emitStringConcat(f *File, pdu parse.PDUStruct) {
	f.Comment("String returns the fields of s as text, for printing. It allocates the")
	f.Comment("string.")
	f.Func().Params(Id("s").Op("*").Id(pdu.Name)).Id("String").Params().String().BlockFunc(func(g *Group) {
		g.Id("_ret").Op(":=").Lit(pdu.Name + "{ ")

		var dispatchFields []parse.Field
		regularParts := []string{}
		regularArgs := []Code{}

		for _, field := range pdu.Fields {
			if field.Skip {
				fmtToken, fmtArgs := toStringFieldFormat(field, pdu)
				if fmtToken == "" {
					continue
				}
				regularParts = append(regularParts, field.Name+": "+fmtToken)
				regularArgs = append(regularArgs, fmtArgs...)
				continue
			}
			if field.Kind == parse.FieldDispatch {
				dispatchFields = append(dispatchFields, field)
				continue
			}
			if field.Fallback {
				continue
			}
			if field.Stride > 0 && field.ArrayLen > 0 {
				if len(regularParts) > 0 {
					fmtStr := strings.Join(regularParts, ", ") + ", "
					allArgs := append([]Code{Lit(fmtStr)}, regularArgs...)
					g.Id("_ret").Op("+=").Qual("fmt", "Sprintf").Call(allArgs...)
					regularParts = nil
					regularArgs = nil
				}
				g.Id("_ret").Op("+=").Lit(field.Name + ": [")
				g.For(Id("_i").Op(":=").Range().Id("s").Dot(field.Name)).Block(
					If(Id("_i").Op(">").Lit(0)).Block(
						Id("_ret").Op("+=").Lit(", "),
					),
					Id("_ret").Op("+=").Id("s").Dot(field.Name).Index(Id("_i")).Dot("String").Call(),
				)
				g.Id("_ret").Op("+=").Lit("]")
				continue
			}
			fmtToken, fmtArgs := toStringFieldFormat(field, pdu)
			if fmtToken == "" {
				continue
			}
			regularParts = append(regularParts, field.Name+": "+fmtToken)
			regularArgs = append(regularArgs, fmtArgs...)
		}

		if len(regularParts) > 0 && len(dispatchFields) > 0 {
			fmtStr := strings.Join(regularParts, ", ") + ", "
			allArgs := append([]Code{Lit(fmtStr)}, regularArgs...)
			g.Id("_ret").Op("+=").Qual("fmt", "Sprintf").Call(allArgs...)
			regularParts = nil
			regularArgs = nil
		}

		if len(dispatchFields) > 0 {
			g.Switch().BlockFunc(func(sw *Group) {
				for _, field := range dispatchFields {
					sw.Case(Id("s").Dot(field.Name).Op("!=").Nil()).Block(
						Id("_ret").Op("+=").Id("s").Dot(field.Name).Dot("String").Call(),
					)
				}
				if fb := fallbackField(pdu); fb != nil {
					sw.Default().Block(
						Id("_ret").Op("+=").Qual("fmt", "Sprintf").Call(Lit(fb.Name+": %x"), Id("s").Dot(fb.Name)),
					)
				}
			})
		}

		if len(regularParts) > 0 {
			fmtStr := ", " + strings.Join(regularParts, ", ")
			allArgs := append([]Code{Lit(fmtStr)}, regularArgs...)
			g.Id("_ret").Op("+=").Qual("fmt", "Sprintf").Call(allArgs...)
		}

		g.Id("_ret").Op("+=").Lit(" }")
		g.Return(Id("_ret"))
	})
}

// toStringFieldFormat returns the fmt format token and arguments for a field in String.
// Returns empty string if the field should be skipped.
func toStringFieldFormat(field parse.Field, pdu parse.PDUStruct) (string, []Code) {
	src := Id("s").Dot(field.Name)

	if field.Skip {
		switch field.Name {
		case fecFieldName:
			return "{BitsChecked: %d, ErrorsCorrected: %d, Uncorrectable: %t}", []Code{
				src.Clone().Dot("BitsChecked"),
				src.Clone().Dot("ErrorsCorrected"),
				src.Clone().Dot("Uncorrectable"),
			}
		default:
			if pdu.IsInput(field.Name) {
				return "%v", []Code{src.Clone()}
			}
			return "", nil
		}
	}

	switch field.Kind {
	case parse.FieldBool:
		return "%t", []Code{src}
	case parse.FieldUint:
		return "%d", []Code{src}
	case parse.FieldInt:
		return "%d", []Code{src}
	case parse.FieldEnum:
		return "%s", []Code{src}
	case parse.FieldRaw:
		return "%x", []Code{src}
	case parse.FieldPacked:
		return "%v", []Code{src}
	case parse.FieldDelegate:
		if field.DelegateNoPtr {
			return "%s", []Code{src}
		}
		return "%s", []Code{src.Clone().Dot("String").Call()}
	case parse.FieldLongitude, parse.FieldLatitude:
		return "%f", []Code{src}
	case parse.FieldDispatch:
		return "", nil
	default:
		return "%v", []Code{src}
	}
}

// emitFieldDecode generates the decode of a single field from the packed
// bits data.
func emitFieldDecode(g *Group, field parse.Field, pdu parse.PDUStruct) {
	target := Id("result").Dot(field.Name)

	if len(field.ExtraBitRanges) > 0 {
		emitNonContiguousDecode(g, field, pdu)
		return
	}

	switch field.Kind {
	case parse.FieldBool:
		g.Add(target).Op("=").Id("data").Index(Lit(field.BitStart / 8)).Op("&").
			Add(hexByte(0x80 >> (field.BitStart % 8))).Op("!=").Lit(0)

	case parse.FieldUint, parse.FieldEnum:
		g.Add(target).Op("=").Add(castUint(field, pdu, readUint(field)))

	case parse.FieldInt:
		if field.Signed {
			g.Add(target).Op("=").Add(qualType(field, pdu)).Call(signExtend(field, Uint32().Call(readUint(field))))
			break
		}
		g.Add(target).Op("=").Add(castUint(field, pdu, readUint(field)))

	case parse.FieldRaw, parse.FieldPacked:
		addAll(g, copyBits(fieldOf("result", field.Name), 0, dataBuf, field.BitStart, field.BitWidth))

	case parse.FieldDelegate:
		emitDelegateDecode(g, field, pdu)

	case parse.FieldLongitude, parse.FieldLatitude:
		// Two's complement value scaled by span/2^width (ETSI TS 102 361-2 clause 7.2.16, clause 7.2.17).
		g.Add(target).Op("=").Float64().Call(signExtend(field, Uint32().Call(readUint(field)))).
			Op("*").Lit(coordSpan(field)).Op("/").Parens(Lit(1).Op("<<").Lit(field.BitWidth))

	case parse.FieldDispatch:
	}
}

// emitDelegateDecode generates the decode of a delegate field. A delegate of
// this package decodes from packed bits; a delegate of another package
// decodes from bit.Bit values through its exported Decode function.
func emitDelegateDecode(g *Group, field parse.Field, pdu parse.PDUStruct) {
	target := Id("result").Dot(field.Name)
	if field.DelegateNoPtr && field.Stride == 0 {
		g.Add(target).Op("=").Add(castUint(field, pdu, readUint(field)))
		return
	}
	width := field.BitEnd - field.BitStart + 1
	if field.Stride > 0 && field.ArrayLen > 0 {
		width = field.Stride
	}
	tmpVar := "_" + strings.ToLower(field.Name[:1]) + field.Name[1:] + "Bytes"
	var decl, fill, call Code
	if field.IsQualified {
		tmpVar = "_" + strings.ToLower(field.Name[:1]) + field.Name[1:] + "Bits"
		decl = Var().Id(tmpVar).Index(Lit(width)).Qual(bitPkg, "Bit")
		call = Qual(resolveImportPath(field.TypePkg, pdu.SourceFile), "Decode"+field.TypeName).Call(Id(tmpVar))
	} else {
		decl = Var().Id(tmpVar).Index(Lit(packedSize(width))).Byte()
		call = Id(bytesDecodeName(field.TypeName, false)).Call(Id(tmpVar))
	}

	if field.Stride > 0 && field.ArrayLen > 0 {
		start := Lit(field.BitStart).Op("+").Id("_i").Op("*").Lit(field.Stride)
		if field.IsQualified {
			fill = Qual(bitsPkg, "Unpack").Call(Id(tmpVar).Index(Empty(), Empty()), Id("data").Index(Empty(), Empty()), start)
		} else {
			fill = Qual(bitsPkg, "Copy").Call(Id(tmpVar).Index(Empty(), Empty()), Lit(0), Id("data").Index(Empty(), Empty()), start, Lit(field.Stride))
		}
		g.For(Id("_i").Op(":=").Lit(0), Id("_i").Op("<").Lit(field.ArrayLen), Id("_i").Op("++")).Block(
			decl, fill, target.Clone().Index(Id("_i")).Op("=").Add(call),
		)
		return
	}

	g.Add(decl)
	if field.IsQualified {
		g.Qual(bitsPkg, "Unpack").Call(Id(tmpVar).Index(Empty(), Empty()), Id("data").Index(Empty(), Empty()), Lit(field.BitStart))
	} else {
		addAll(g, copyBits(idOf(tmpVar), 0, dataBuf, field.BitStart, width))
	}
	g.Add(target).Op("=").Add(call)
}

// emitEncode generates the encodeBytes method of a PDU struct, which returns
// the full codeword, FEC parity included, packed most significant bit
// first, or an error when a field value does not fit its bits, and the
// Encode method, which returns the codeword of encodeBytes as bit.Bit
// values.
func emitEncode(f *File, pdu parse.PDUStruct, ev *errVars) error {
	codec, hasFEC, err := resolveCodec(pdu)
	if err != nil {
		return err
	}

	outputSize := pdu.InputSize
	if hasFEC {
		outputSize = codec.InputSize
	}
	enc := encoder{pdu: pdu, bytes: packedSize(outputSize), errs: ev}

	f.Comment("encodeBytes encodes " + docObject(pdu))
	f.Comment("It returns the bits of Encode packed, the first bit most significant.")
	var genErr error
	f.Func().Params(Id("s").Op("*").Id(pdu.Name)).Id("encodeBytes").Params().Params(
		Index(Lit(enc.bytes)).Byte(),
		Error(),
	).BlockFunc(func(g *Group) {
		g.Var().Id("data").Index(Lit(enc.bytes)).Byte()
		if err := enc.fields(g); err != nil {
			genErr = err
			return
		}
		switch {
		case pdu.CRC != nil:
			emitCRCEncode(g, pdu, outputSize)
		case hasFEC && codec.PackedBytes:
			if err := emitPackedFECEncode(g, enc, codec); err != nil {
				genErr = err
				return
			}
		case hasFEC:
			g.Id("_cw").Op(":=").Qual(codec.ImportPath, codec.EncodeFn).Call(Uint8().Call(readPacked(dataBuf, 0, codec.DataBits)))
			addAll(g, writePacked(dataBuf, 0, codec.InputSize, Uint64().Call(Id("_cw")), "_cwBits"))
		}
		g.Return(Id("data"), Nil())
	})
	if genErr != nil {
		return genErr
	}
	f.Line()

	f.Comment("Encode encodes " + docObject(pdu))
	f.Func().Params(Id("s").Op("*").Id(pdu.Name)).Id("Encode").Params().Params(
		Index(Lit(outputSize)).Qual(bitPkg, "Bit"),
		Error(),
	).Block(
		List(Id("_b"), Err()).Op(":=").Id("s").Dot("encodeBytes").Call(),
		If(Err().Op("!=").Nil()).Block(Return(Index(Lit(outputSize)).Qual(bitPkg, "Bit").Values(), Err())),
		Var().Id("data").Index(Lit(outputSize)).Qual(bitPkg, "Bit"),
		For(Id("_i").Op(":=").Range().Lit(outputSize)).Block(
			Id("data").Index(Id("_i")).Op("=").Qual(bitPkg, "Bit").Call(
				Id("_b").Index(Id("_i").Op("/").Lit(8)).Op(">>").Parens(Lit(7).Op("-").Id("_i").Op("%").Lit(8)).Op("&").Lit(1),
			),
		),
		Return(Id("data"), Nil()),
	)
	return nil
}

// encoder carries the PDU and the packed output size in bytes while
// emitting an encodeBytes body.
type encoder struct {
	pdu   parse.PDUStruct
	bytes int
	errs  *errVars
}

// fail returns a statement that returns a zero codeword and the given error.
func (e encoder) fail(err Code) *Statement {
	return Return(Index(Lit(e.bytes)).Byte().Values(), err)
}

// failRange returns a statement that returns a zero codeword and the static
// *bit.FieldRangeError of field. lo and hi, when not nil, are the range of a
// coordinate field.
func (e encoder) failRange(field parse.Field, lo, hi Code) *Statement {
	signed := field.Signed || field.Kind == parse.FieldLongitude || field.Kind == parse.FieldLatitude
	values := Dict{
		Id("Type"):  Lit(e.pdu.Name),
		Id("Field"): Lit(field.Name),
		Id("Bits"):  Lit(field.BitWidth),
	}
	if signed {
		values[Id("Signed")] = True()
	}
	if lo != nil {
		values[Id("Min")], values[Id("Max")] = lo, hi
	}
	def := Op("&").Qual(bitPkg, "FieldRangeError").Values(values)
	return e.fail(e.errs.get("err"+e.pdu.Name+field.Name+"Range", def))
}

// fields emits the encoding of all fields. It encodes the dispatch fields
// first, because their wide copy (such as data[0:80]) would overwrite outer
// fields that share the bit range, such as Format.
func (e encoder) fields(g *Group) error {
	var regularFields []parse.Field
	var dispatchFields []parse.Field
	for _, field := range e.pdu.Fields {
		if field.Skip {
			continue
		}
		switch {
		case field.Kind == parse.FieldDispatch:
			dispatchFields = append(dispatchFields, field)
		case field.Fallback:
		default:
			regularFields = append(regularFields, field)
		}
	}
	if len(dispatchFields) > 0 {
		e.payload(g, dispatchFields)
		e.dispatch(g, dispatchFields)
	}
	for _, field := range regularFields {
		if field.NoEncode {
			continue
		}
		e.field(g, field)
	}
	for i, c := range e.pdu.Consts {
		e.constant(g, c, i)
	}
	if len(dispatchFields) > 0 {
		return e.checkPayload(g, dispatchFields)
	}
	return nil
}

// payload sets _payload to the name of the one dispatch field that is set,
// or "" if none is, and fails if more than one is set.
func (e encoder) payload(g *Group, fields []parse.Field) {
	g.Id("_payload").Op(":=").Lit("")
	for i, field := range fields {
		set := []Code{Id("_payload").Op("=").Lit(field.Name)}
		if i > 0 {
			set = append([]Code{If(Id("_payload").Op("!=").Lit("")).Block(
				e.fail(e.errs.get("err"+e.pdu.Name+"Payloads", errorsNew(e.pdu.Name+": more than one payload field is set"))),
			)}, set...)
		}
		g.If(Id("s").Dot(field.Name).Op("!=").Nil()).Block(set...)
	}
}

// checkPayload fails if the encoded bits would decode into a different
// dispatch field than the one set. It decodes the fields that select the
// dispatch field from the encoded bits and repeats the decode selection.
func (e encoder) checkPayload(g *Group, fields []parse.Field) error {
	selectors := dispatchSelectors(e.pdu, fields)
	none := "no payload"
	if fb := fallbackField(e.pdu); fb != nil {
		none = fb.Name
	}
	verb := " select "
	if len(selectors) == 1 {
		verb = " selects "
	}
	sel, err := dispatchSelect(fields, e.pdu, func(field parse.Field) []Code {
		return []Code{Id("_want").Op("=").Lit(field.Name)}
	}, nil)
	if err != nil {
		return err
	}
	g.If(Id("_payload").Op("!=").Lit("")).BlockFunc(func(b *Group) {
		b.Var().Id("result").Id(e.pdu.Name)
		for _, name := range selectors {
			if e.pdu.IsInput(name) {
				b.Id("result").Dot(name).Op("=").Id("s").Dot(name)
				continue
			}
			emitFieldDecode(b, *e.pdu.FieldByName(name), e.pdu)
		}
		b.Id("_want").Op(":=").Lit(none)
		b.Add(sel)
		b.If(Id("_payload").Op("!=").Id("_want")).Block(
			e.fail(e.errs.get("err"+e.pdu.Name+"Payload", errorsNew(e.pdu.Name+": the payload field that is set is not the one that "+joinNames(selectors)+strings.TrimRight(verb, " ")))),
		)
	})
	return nil
}

// dispatchSelectors returns the fields that the decode selection of a
// dispatch field reads, in order of first use.
func dispatchSelectors(pdu parse.PDUStruct, fields []parse.Field) []string {
	var names []string
	add := func(name string) {
		for _, n := range names {
			if n == name {
				return
			}
		}
		names = append(names, name)
	}
	add(fields[0].DispatchFieldName)
	if pdu.DispatchIf != nil {
		add(pdu.DispatchIf.Field)
	}
	for _, f := range fields {
		if f.When != nil {
			add(f.When.Field)
		}
	}
	return names
}

func joinNames(names []string) string {
	if len(names) == 1 {
		return names[0]
	}
	return strings.Join(names[:len(names)-1], ", ") + " and " + names[len(names)-1]
}

// dispatch generates a switch that encodes the active dispatch field.
func (e encoder) dispatch(g *Group, fields []parse.Field) {
	bitStart := fields[0].BitStart
	n := fields[0].BitEnd - bitStart + 1

	g.Switch().BlockFunc(func(sw *Group) {
		for _, field := range fields {
			store := copyBits(dataBuf, bitStart, idOf("_pduBytes"), 0, n)
			body := make([]Code, 0, 2+len(store))
			body = append(body,
				List(Id("_pduBytes"), Err()).Op(":=").Id("s").Dot(field.Name).Dot("encodeBytes").Call(),
				If(Err().Op("!=").Nil()).Block(e.fail(Err())),
			)
			body = append(body, store...)
			sw.Case(Id("s").Dot(field.Name).Op("!=").Nil()).Block(body...)
		}
		if fb := fallbackField(e.pdu); fb != nil {
			sw.Default().BlockFunc(func(d *Group) {
				e.raw(d, *fb)
			})
		}
	})
}

// emitCRCEncode generates the CRC calculation and its store into the
// packed bits data, for a byte-level CRC (CRC-CCITT) or a bit-level CRC
// (CRC-8).
func emitCRCEncode(g *Group, pdu parse.PDUStruct, outputSize int) {
	algo := crcAlgorithms[pdu.CRC.Algorithm]
	if algo.BitLevel {
		dataBits := outputSize - algo.CRCBits
		value := Uint64().Call(Qual(crcPkg, algo.CalcFn).Call(Id("data").Index(Empty(), Empty()), Lit(dataBits)))
		addAll(g, writePacked(dataBuf, dataBits, algo.CRCBits, value, "_crcVal"))
		return
	}

	dataBytes := outputSize/8 - 2
	g.Id("_crcVal").Op(":=").Qual(crcPkg, algo.CalcFn).Call(Id("data").Index(Empty(), Lit(dataBytes)))
	high := Byte().Call(Id("_crcVal").Op(">>").Lit(8))
	low := Byte().Call(Id("_crcVal"))
	if pdu.CRC.HasMask {
		highByte, lowByte := maskBytes(pdu.CRC.Mask)
		high = high.Op("^").Add(hexByte(highByte))
		low = low.Op("^").Add(hexByte(lowByte))
	}
	g.Id("data").Index(Lit(dataBytes)).Op("=").Add(high)
	g.Id("data").Index(Lit(dataBytes + 1)).Op("=").Add(low)
}

// emitPackedFECEncode generates the Reed-Solomon encoding of the packed bits
// data.
func emitPackedFECEncode(g *Group, enc encoder, codec *FECCodecInfo) error {
	pdu := enc.pdu
	g.Id("_encoded").Op(":=").Qual(codec.ImportPath, encodeFnName).Call(
		Index(Lit(codec.DataBytes)).Byte().Parens(Id("data").Index(Empty(), Lit(codec.DataBytes))))

	var noMask Code
	if pdu.FECMask != nil {
		noMask = enc.fail(enc.errs.get("err"+pdu.Name+pdu.FECMask.Field+"Mask", errorsNew(pdu.Name+"."+pdu.FECMask.Field+": no FEC mask for the value")))
	}
	if err := emitFECMask(g, pdu, codec, Id("s"), "_encoded", noMask); err != nil {
		return err
	}
	g.Id("data").Op("=").Id("_encoded")
	return nil
}

// field generates the encode logic for a single field.
func (e encoder) field(g *Group, field parse.Field) {
	source := Id("s").Dot(field.Name)

	if isIntegerField(field) {
		e.integer(g, field)
		return
	}

	switch field.Kind {
	case parse.FieldUint, parse.FieldInt, parse.FieldEnum:
	case parse.FieldBool:
		k := field.BitStart / 8
		g.If(source.Clone()).Block(
			Id("data").Index(Lit(k)).Op("|=").Add(hexByte(0x80 >> (field.BitStart % 8))),
		)

	case parse.FieldRaw, parse.FieldPacked:
		e.raw(g, field)

	case parse.FieldDelegate:
		e.delegate(g, field)

	case parse.FieldLongitude, parse.FieldLatitude:
		raw := "_raw" + field.Name
		half := 1 << (field.BitWidth - 1)
		limit := coordSpan(field) / 2
		// Negated form also rejects NaN.
		g.If(Op("!").Parens(source.Clone().Op(">=").Lit(-limit).Op("&&").Add(source.Clone()).Op("<=").Lit(limit))).Block(
			e.failRange(field, Lit(-limit), Lit(limit)),
		)
		g.Id(raw).Op(":=").Add(coordRaw(field, source.Clone()))
		// +180 degrees longitude rounds to 2^(width-1), which the two's
		// complement store wraps to -180, the same meridian. +90 degrees
		// latitude has no code, so it takes the nearest one.
		if field.Kind == parse.FieldLatitude {
			g.Id(raw).Op("=").Min(Id(raw), Lit(half-1))
		}
		addAll(g, writePacked(dataBuf, field.BitStart, field.BitWidth, Uint64().Call(Int64().Call(Id(raw))), "_val"+field.Name))

	case parse.FieldDispatch:
	}
}

// delegate encodes a delegate field: from the packed bits of a delegate of
// this package, or from the bit.Bit values that the Encode method of a
// delegate of another package returns.
func (e encoder) delegate(g *Group, field parse.Field) {
	source := Id("s").Dot(field.Name)
	method := "encodeBytes"
	suffix := "Bytes"
	if field.IsQualified {
		method, suffix = encodeFnName, "Bits"
	}
	if field.Stride > 0 {
		start := Lit(field.BitStart).Op("+").Id("_i").Op("*").Lit(field.Stride)
		var store Code
		if field.IsQualified {
			store = Qual(bitsPkg, "Pack").Call(Id("data").Index(Empty(), Empty()), start, Id("_elem"+suffix).Index(Empty(), Empty()))
		} else {
			store = Qual(bitsPkg, "Copy").Call(Id("data").Index(Empty(), Empty()), start, Id("_elem"+suffix).Index(Empty(), Empty()), Lit(0), Lit(field.Stride))
		}
		g.For(Id("_i").Op(":=").Lit(0), Id("_i").Op("<").Lit(field.ArrayLen), Id("_i").Op("++")).Block(
			List(Id("_elem"+suffix), Err()).Op(":=").Add(source.Clone().Index(Id("_i"))).Dot(method).Call(),
			If(Err().Op("!=").Nil()).Block(e.fail(Err())),
			store,
		)
		return
	}
	tmpVar := "_" + strings.ToLower(field.Name[:1]) + field.Name[1:] + suffix
	g.List(Id(tmpVar), Err()).Op(":=").Add(source.Clone()).Dot(method).Call()
	g.If(Err().Op("!=").Nil()).Block(e.fail(Err()))
	if field.IsQualified {
		g.Qual(bitsPkg, "Pack").Call(Id("data").Index(Empty(), Empty()), Lit(field.BitStart), Id(tmpVar).Index(Empty(), Empty()))
		return
	}
	addAll(g, copyBits(dataBuf, field.BitStart, idOf(tmpVar), 0, field.BitEnd-field.BitStart+1))
}

// raw encodes a raw or packed byte-array field after checking that its
// padding bits are zero. A packed field has no padding bits.
func (e encoder) raw(g *Group, field parse.Field) {
	n := parse.RawBytes(field.BitWidth)
	if pad := n*8 - field.BitWidth; pad > 0 {
		g.If(Id("s").Dot(field.Name).Index(Lit(n - 1)).Op("&").Lit(1<<pad - 1).Op("!=").Lit(0)).Block(
			e.failRange(field, nil, nil),
		)
	}
	addAll(g, copyBits(dataBuf, field.BitStart, fieldOf("s", field.Name), 0, field.BitWidth))
}

// integer encodes an unsigned, signed, enum or noptr delegate field after
// checking that its value fits the field width.
func (e encoder) integer(g *Group, field parse.Field) {
	source := Id("s").Dot(field.Name)
	w := field.BitWidth
	switch {
	case field.Signed:
		lo, hi := -(1 << (w - 1)), (1<<(w-1))-1
		g.If(Int64().Call(source.Clone()).Op("<").Lit(lo).Op("||").Int64().Call(source.Clone()).Op(">").Lit(hi)).Block(
			e.failRange(field, nil, nil),
		)
	case needsRangeCheck(field):
		g.If(Uint64().Call(source.Clone()).Op(">>").Lit(w).Op("!=").Lit(0)).Block(
			e.failRange(field, nil, nil),
		)
	}

	value := source.Clone()
	if field.GoType != typUint64 {
		value = Uint64().Call(value)
	}
	storeBits(g, field.Ranges(), value, "_val"+field.Name)
}

// constant encodes a dmr:const directive.
func (e encoder) constant(g *Group, c parse.ConstDirective, idx int) {
	var value *Statement
	if n, err := strconv.ParseUint(c.Value, 0, 64); err == nil {
		value = Uint64().Call(Id(strconv.FormatUint(n, 10)))
	} else {
		value = Uint64().Call(emitDispatchConstant(c.Value, e.pdu))
	}
	storeBits(g, c.Ranges, value, fmt.Sprintf("_const%d", idx))
}

// storeBits stores the uint64 value MSB-first across ranges of the packed
// bits data. A value that spans bytes or ranges goes through the temporary
// variable tmp.
func storeBits(g *Group, ranges [][2]int, value *Statement, tmp string) {
	if len(ranges) == 1 {
		addAll(g, writePacked(dataBuf, ranges[0][0], ranges[0][1]-ranges[0][0]+1, value, tmp))
		return
	}

	g.Id(tmp).Op(":=").Add(value)
	remaining := 0
	for _, r := range ranges {
		remaining += r[1] - r[0] + 1
	}
	for _, r := range ranges {
		remaining -= r[1] - r[0] + 1
		seg := Id(tmp)
		if remaining > 0 {
			seg = Id(tmp).Op(">>").Lit(remaining)
		}
		addAll(g, writePacked(dataBuf, r[0], r[1]-r[0]+1, seg, ""))
	}
}

// isIntegerField reports whether a field is stored as a plain integer value.
func isIntegerField(field parse.Field) bool {
	switch field.Kind {
	case parse.FieldUint, parse.FieldInt, parse.FieldEnum:
		return true
	case parse.FieldDelegate:
		return field.DelegateNoPtr && field.Stride == 0
	case parse.FieldBool, parse.FieldRaw, parse.FieldPacked, parse.FieldLongitude, parse.FieldLatitude, parse.FieldDispatch:
	}
	return false
}

// needsRangeCheck reports whether an unsigned field's Go type can hold values
// wider than the field.
func needsRangeCheck(field parse.Field) bool {
	switch field.BaseType {
	case typUint8, "byte":
		return field.BitWidth < 8
	case typUint16:
		return field.BitWidth < 16
	case typUint32:
		return field.BitWidth < 32
	}
	return true
}

// emitNonContiguousDecode generates the decode of a non-contiguous uint field.
// For bits:3+12-15, bit 3 is the MSB and bits 12 to 15 are the low nibble.
func emitNonContiguousDecode(g *Group, field parse.Field, pdu parse.PDUStruct) {
	tmpName := "_tmp" + field.Name
	g.Var().Id(tmpName).Uint64()
	for i, r := range field.Ranges() {
		read := readPacked(dataBuf, r[0], r[1]-r[0]+1)
		if i == 0 {
			g.Id(tmpName).Op("=").Add(read)
			continue
		}
		g.Id(tmpName).Op("<<=").Lit(r[1] - r[0] + 1)
		g.Id(tmpName).Op("|=").Add(read)
	}

	target := Id("result").Dot(field.Name)
	tmp := Id(tmpName)
	if field.Signed {
		g.Add(target).Op("=").Add(qualType(field, pdu)).Call(signExtend(field, Uint32().Call(tmp)))
		return
	}
	g.Add(target).Op("=").Add(castUint(field, pdu, tmp))
}

// maskBytes splits a 16-bit CRC mask into its high and low bytes.
func maskBytes(mask uint16) (byte, byte) {
	var b [2]byte
	binary.BigEndian.PutUint16(b[:], mask)
	return b[0], b[1]
}

// readUint reads a contiguous field from the packed bits data as a uint64.
func readUint(field parse.Field) *Statement {
	return readPacked(dataBuf, field.BitStart, field.BitEnd-field.BitStart+1)
}

// castUint converts the uint64 expression v to the type of field.
func castUint(field parse.Field, pdu parse.PDUStruct, v *Statement) *Statement {
	if field.GoType == typUint64 {
		return v
	}
	return qualType(field, pdu).Call(v)
}

// signExtend converts a width-bit two's complement value held in a uint32
// expression to int32.
func signExtend(field parse.Field, raw *Statement) *Statement {
	shift := 32 - field.BitWidth
	if shift == 0 {
		return Int32().Call(raw)
	}
	return Int32().Call(raw.Op("<<").Lit(shift)).Op(">>").Lit(shift)
}

// coordSpan returns the full range in degrees of a latitude or longitude field.
func coordSpan(field parse.Field) float64 {
	if field.Kind == parse.FieldLongitude {
		return 360
	}
	return 180
}

// coordRaw converts a coordinate in degrees to the nearest raw step count.
func coordRaw(field parse.Field, value *Statement) *Statement {
	return Qual("math", "Round").Call(
		value.Op("*").Parens(Lit(1).Op("<<").Lit(field.BitWidth)).Op("/").Lit(coordSpan(field)),
	)
}

// inputParamName converts a dmr:input field name to its Decode parameter name.
func inputParamName(field string) string {
	name := strings.ToLower(field[:1]) + field[1:]
	switch name {
	case "data", "result", "corrected", "dst", "p":
		return "_" + name
	}
	return name
}

func qualType(field parse.Field, pdu parse.PDUStruct) *Statement {
	if field.IsQualified {
		importPath := resolveImportPath(field.TypePkg, pdu.SourceFile)
		return Qual(importPath, field.TypeName)
	}
	return Id(field.GoType)
}
