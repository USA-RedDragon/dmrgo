type options struct {
	update    *bool
	check     *bool
	noSweep   *bool
	sheetOnly *bool
}

func defineFlags(fs *flag.FlagSet) options {
	return options{
		update:    fs.Bool("update-readme", false, "run the long sweep and the datasheet tests, then rewrite the blocks of docs/rx.md and the graphs"),
		check:     fs.Bool("check-readme", false, "fail when a block of docs/rx.md or a graph differs from the committed data"),
		noSweep:   fs.Bool("no-sweep", false, "with -update-readme, render the committed data without the sweep"),
		sheetOnly: fs.Bool("sheet", false, "with -update-readme, measure only the eye diagrams, offset, clock and late entry data (TestRxSheet), then render"),
	}
}

func main() {
	o := defineFlags(flag.CommandLine)
	flag.Parse()
	if *o.update == *o.check {
		fmt.Fprintln(os.Stderr, "rxbench: give -update-readme or -check-readme")
		os.Exit(2)
	}
	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		fmt.Fprintln(os.Stderr, "rxbench: cannot find the rxbench source directory")
		os.Exit(1)
	}
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt)
	sweep := sweepNone
	switch {
	case *o.update && *o.sheetOnly:
		sweep = sweepSheet
	case *o.update && !*o.noSweep:
		sweep = sweepFull
	}
	err := run(ctx, filepath.Join(filepath.Dir(thisFile), "..", ".."), *o.update, sweep)
	stop()
	if err != nil {
		fmt.Fprintln(os.Stderr, "rxbench:", err)
		os.Exit(1)
	}
}

var errStale = errors.New("out of date: run go run -C cmd/rxbench . -update-readme")

const (
	sweepNone = iota
	sweepSheet
	sweepFull
)

const plotCopyPath = "v2/internal/fsktx/plot_gen_test.go"

func plotForTx(root string) ([]byte, error) {
	src, err := os.ReadFile(filepath.Join(root, "cmd/rxbench/plot.go"))
	if err != nil {
		return nil, err
	}
	body, ok := bytes.CutPrefix(src, []byte("package main\n"))
	if !ok {
		return nil, errors.New("cmd/rxbench/plot.go does not start with package main")
	}
	return append([]byte("// Code generated by go run -C cmd/rxbench . -update-readme from cmd/rxbench/plot.go. DO NOT EDIT.\n\npackage fsktx\n"), body...), nil
}

func goTest(ctx context.Context, root, test, env string) error {
	cmd := exec.CommandContext(ctx, "go", "test", "-C", filepath.Join(root, "v2"), "-count=1", "-run", "^"+test+"$", "-timeout", "6h", "./rf")
	if env != "" {
		cmd.Env = append(os.Environ(), env)
	}
	cmd.Stdout, cmd.Stderr = os.Stderr, os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("%s: %w", test, err)
	}
	return nil
}

func replaceBlock(doc []byte, begin, end string, block []byte) ([]byte, error) {
	i, j := bytes.Index(doc, []byte(begin)), bytes.Index(doc, []byte(end))
	if i < 0 || j < i {
		return nil, fmt.Errorf("%s has no %s ... %s block", docName, begin, end)
	}
	return append(append(append([]byte{}, doc[:i+len(begin)]...), block...), doc[j:]...), nil
}

func run(ctx context.Context, root string, update bool, sweep int) error {
	if sweep == sweepFull {
		if err := goTest(ctx, root, "TestRxBench", "DMRRF_RXBENCH=full"); err != nil {
			return err
		}
		if os.Getenv("DMRRF_SLCBENCH") != "" {
			if err := goTest(ctx, root, "TestShortLCBench", ""); err != nil {
				return err
			}
		}
	}
	if sweep >= sweepSheet {
		if err := goTest(ctx, root, "TestRxSheet", "DMRRF_RXSHEET=1"); err != nil {
			return err
		}
	}
	d, err := load(filepath.Join(root, "v2/rf/testdata"))
	if err != nil {
		return err
	}
	graphs := renderGraphs(d)
	maps.Copy(graphs, sheetGraphs(d))
	plotCopy, err := plotForTx(root)
	if err != nil {
		return err
	}
	readmePath := filepath.Join(root, docName)
	readme, err := os.ReadFile(readmePath)
	if err != nil {
		return err
	}
	next := readme
	for _, blk := range []struct {
		begin, end string
		body       []byte
	}{
		{specsBegin, specsEnd, renderSpecs(d)}, {limitsBegin, limitsEnd, renderLimits(d)}, {beginMarker, endMarker, renderBlock(d)},
		{shortLCBegin, shortLCEnd, renderShortLC(d.shortLC)}, {extBegin, extEnd, renderExt(d.ext)},
		{extMethodsBegin, extMethodsEnd, renderExtMethods(d.ext)},
	} {
		if next, err = replaceBlock(next, blk.begin, blk.end, blk.body); err != nil {
			return err
		}
	}
	stale := !bytes.Equal(next, readme)
	files := map[string][]byte{plotCopyPath: plotCopy}
	for name, svg := range graphs {
		files[filepath.Join(graphDir, name)] = svg
	}
	for name, svg := range files {
		p := filepath.Join(root, name)
		old, err := os.ReadFile(p)
		if err != nil || !bytes.Equal(old, svg) {
			stale = true
			if update {
				if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
					return err
				}
				if err := os.WriteFile(p, svg, 0o600); err != nil {
					return err
				}
			}
		}
	}
	if !update {
		if stale {
			return errStale
		}
		return nil
	}
	return os.WriteFile(readmePath, next, 0o600)
}

type score struct {
	Truth int `json:"truth"`
	Exact int `json:"exact"`
}

type point struct {
	CN       float64           `json:"cn"`
	Payloads map[string]*score `json:"payloads"`
}

type tier struct {
	Mode         string  `json:"mode"`
	Tier         int     `json:"tier"`
	Full         []point `json:"full"`
	NsPerSecond  float64 `json:"ns_per_second"`
	WorstNs      float64 `json:"worst_ns_per_second"`
	RAMBytes     int     `json:"ram_bytes"`
	Allocs       float64 `json:"allocs"`
	FalsePerHour float64 `json:"false_per_hour"`
}

type bench struct {
	Machine string `json:"machine"`
	Tiers   []tier `json:"tiers"`
}

type curve struct {
	EbN0  []float64 `json:"ebn0"`
	Truth []int     `json:"truth"`
	Exact []int     `json:"exact"`
	Bound string    `json:"bound"`
}

func (c curve) recovery() []float64 {
	y := make([]float64, len(c.EbN0))
	for i := range y {
		if i < len(c.Truth) && c.Truth[i] > 0 {
			y[i] = float64(c.Exact[i]) / float64(c.Truth[i])
		}
	}
	return y
}

const (
	statusExact = "exact"
	statusLower = "lower bound"
)

type floorPair struct {
	Any    curve  `json:"any"`
	DMR    curve  `json:"dmr"`
	Status string `json:"status"`
}

type floors struct {
	Source   string               `json:"source"`
	Payloads map[string]floorPair `json:"payloads"`
}

type curves struct {
	Source   string           `json:"source"`
	Payloads map[string]curve `json:"payloads"`
}

type recording struct {
	Name  string  `json:"name"`
	CN    float64 `json:"cn"`
	Truth int     `json:"truth"`
	Exact []int   `json:"exact"`
}

type data struct {
	bench      bench
	floor      floors
	aware      curves
	recordings []recording
	shortLC    shortLCData
	ext        extData
	sheet      sheet
	mcu        mcuData
}

func load(dir string) (data, error) {
	var d data
	for name, v := range map[string]any{"rxbench.json": &d.bench, "rxbench_floor.json": &d.floor, "rxbench_aware.json": &d.aware, "rxbench_recordings.json": &d.recordings,
		"rxbench_shortlc.json": &d.shortLC, "extcmp.json": &d.ext, "extcmp_m4.json": &d.ext.m4, "rxsheet.json": &d.sheet, "rxbench_mcu.json": &d.mcu} {
		if err := loadJSON(filepath.Join(dir, name), v); err != nil {
			return d, err
		}
	}
	return d, nil
}

const (
	noiseBandHz = 12500.0
	symbolRate  = 4800
	bitRate     = 2 * symbolRate
	recoverMin  = 0.9
)

func pct(v float64) string { return strconv.FormatFloat(math.Round(v*100), 'f', -1, 64) + "%" }

func bandText() string { return strconv.FormatFloat(noiseBandHz/1000, 'f', -1, 64) + " kHz" }

func cnToEbN0(cn float64) float64 { return cn + 10*math.Log10(noiseBandHz/bitRate) }

func payloadNames() [][2]string {
	return [][2]string{
		{keyAMBE, "Voice frame (AMBE+2, 49 bits)"},
		{"ambe_c0c1", "Voice frame, protected bits (C0 and C1)"},
		{keyRate12, "Data block, rate 1/2"},
		{keyRate34, "Data block, rate 3/4"},
		{"rate1", "Data block, rate 1"},
		{keyCSBK, labelCSBK},
		{"lc", "Voice LC header and terminator"},
		{"header", "Data header"},
		{keyELC, labelELC},
		{"emb", "EMB"},
		{"slottype", "Slot type"},
		{"sync", "SYNC detection"},
	}
}

const (
	modeAudio = "audio"
	modeIQ    = "iq"
	modeIQLow = "iqlow"
)

func modes() [][3]string {
	return [][3]string{{modeAudio, "FM discriminator audio", "Audio"}, {modeIQLow, "I/Q at 9.6 kHz", "Low-rate I/Q"}, {modeIQ, inputIQ, inputIQ}}
}

func modeLabel(m string) string {
	for _, v := range modes() {
		if v[0] == m {
			return v[2]
		}
	}
	return m
}

func shortName(t tier) string {
	return modeLabel(t.Mode) + " tier " + strconv.Itoa(t.Tier)
}

const inputIQ = "I/Q"

func inputName(t tier) string {
	if t.Mode == modeAudio {
		return "FM audio"
	}
	return inputIQ
}

func inputRate(t tier) string {
	if t.Mode == modeIQ {
		return "48"
	}
	return "9.6"
}

type crossing struct {
	ebn0      float64
	ok, below bool
}

func at90(x, y []float64) crossing {
	if len(y) > 0 && y[0] >= recoverMin {
		return crossing{x[0], true, true}
	}
	for i := 1; i < len(x); i++ {
		if y[i-1] < recoverMin && y[i] >= recoverMin {
			return crossing{x[i-1] + (recoverMin-y[i-1])/(y[i]-y[i-1])*(x[i]-x[i-1]), true, false}
		}
	}
	return crossing{}
}

func tierCurve(t tier, k string) (x, y []float64) {
	for _, p := range t.Full {
		if s := p.Payloads[k]; s != nil && s.Truth > 0 {
			x = append(x, cnToEbN0(p.CN))
			y = append(y, float64(s.Exact)/float64(s.Truth))
		}
	}
	return x, y
}

func ramCell(n int) string {
	if n < 10<<10 {
		return f1(float64(n) / 1024)
	}
	return grouped(int64((n + 1023) / 1024))
}

func grouped(n int64) string {
	s := strconv.FormatInt(n, 10)
	for i := len(s) - 3; i > 0; i -= 3 {
		s = s[:i] + "," + s[i:]
	}
	return s
}

func f1(v float64) string { return strconv.FormatFloat(math.Round(v*10)/10+0, 'f', 1, 64) }

func renderBlock(d data) []byte {
	var b strings.Builder
	b.WriteString("\n### Error rate\n\nError rate against Eb/N0 of each tier, with the 4FSK floor dashed. Points with no errors are left out.\n\n")
	for _, m := range modes() {
		b.WriteString("#### " + m[1] + "\n\n")
		for _, g := range graphs() {
			b.WriteString("![" + g.title + ", " + m[1] + ": " + strings.ToLower(g.rate) + " against Eb/N0, references and tiers](" + imgDir + m[0] + "/" + g.key + ".svg)\n")
		}
		b.WriteString("\n")
	}
	renderSheetGraphs(&b, d)
	renderSensitivity(&b, d)
	var rec []tier
	var cols []int
	for i, t := range d.bench.Tiers {
		for _, r := range d.recordings {
			if i < len(r.Exact) && r.Exact[i] >= 0 {
				rec, cols = append(rec, t), append(cols, i)
				break
			}
		}
	}
	b.WriteString("### Real recordings\n\n")
	b.WriteString("Voice frames recovered exactly from captures of a Motorola XPR 8400 repeater with an RTL-SDR.\n\n")
	cols0 := make([]string, 0, 3+len(rec))
	cols0 = append(cols0, "Recording", "C/N (dB)", "Frames")
	for _, t := range rec {
		cols0 = append(cols0, shortName(t))
	}
	b.WriteString(tableHead(cols0...))
	for _, r := range d.recordings {
		b.WriteString("| " + r.Name + " | " + f1(r.CN) + " | " + strconv.Itoa(r.Truth) + " |")
		for _, i := range cols {
			b.WriteString(" " + strconv.Itoa(r.Exact[i]) + " |")
		}
		b.WriteString("\n")
	}
	b.WriteString("\n")
	return []byte(b.String())
}

func renderSensitivity(b *strings.Builder, d data) {
	b.WriteString("### Sensitivity per payload type\n\n")
	b.WriteString("Eb/N0 in dB for " + pct(recoverMin) + " of the frames recovered exactly. [The floors](#the-floors) defines each floor.\n\n")
	b.WriteString(tableHead("Payload", "4FSK floor", "DMR floor", "Code cost", "Code-aware"))
	for _, p := range payloadNames() {
		cells := []string{p[1], "-", "-", "-", "-"}
		if f, ok := d.floor.Payloads[p[0]]; ok {
			cells[1] = dbCell(at90(f.Any.EbN0, f.Any.recovery()))
			cells[2] = dmrCell(f)
			cells[3] = costCell(d, p[0])
		}
		if c, ok := d.aware.Payloads[p[0]]; ok {
			cells[4] = dbCell(at90(c.EbN0, c.recovery()))
		}
		b.WriteString("| " + strings.Join(cells, " | ") + " |\n")
	}
	cols := make([]string, 0, 1+len(d.bench.Tiers))
	cols = append(cols, "Payload")
	for _, t := range d.bench.Tiers {
		cols = append(cols, shortName(t))
	}
	b.WriteString("\n" + tableHead(cols...))
	for _, p := range payloadNames() {
		cells := make([]string, 0, 1+len(d.bench.Tiers))
		cells = append(cells, p[1])
		for _, t := range d.bench.Tiers {
			cells = append(cells, dbCell(at90(tierCurve(t, p[0]))))
		}
		b.WriteString("| " + strings.Join(cells, " | ") + " |\n")
	}
	b.WriteString("\n")
}

func dmrCell(f floorPair) string {
	c := at90(f.DMR.EbN0, f.DMR.recovery())
	switch {
	case f.Status == statusExact:
		return dbCell(c)
	case f.Status == statusLower && c.ok && !c.below:
		return "at least " + dbCell(c)
	}
	return "-"
}

type span struct {
	lo, hi     float64
	loOK, hiOK bool
}

func (s span) text(unit string) string {
	switch {
	case s.loOK && s.hiOK:
		lo := min(s.lo, s.hi)
		if f1(lo) == f1(s.hi) {
			return f1(s.hi) + unit
		}
		return f1(lo) + " to " + f1(s.hi) + unit
	case s.hiOK:
		return "at most " + f1(s.hi) + unit
	case s.loOK:
		return "at least " + f1(s.lo) + unit
	}
	return "-"
}

func gap(a, b crossing) (float64, bool) {
	return a.ebn0 - b.ebn0, a.ok && b.ok && !a.below && !b.below
}

func referenceCrossings(d data, k string) (dmr, anyCode, aware crossing, status string, ok bool) {
	f, ok := d.floor.Payloads[k]
	if !ok {
		return crossing{}, crossing{}, crossing{}, "", false
	}
	if c, has := d.aware.Payloads[k]; has {
		aware = at90(c.EbN0, c.recovery())
	}
	return at90(f.DMR.EbN0, f.DMR.recovery()), at90(f.Any.EbN0, f.Any.recovery()), aware, f.Status, true
}

func costCell(d data, k string) string {
	dmr, anyCode, aware, status, ok := referenceCrossings(d, k)
	if !ok {
		return "-"
	}
	var s span
	s.lo, s.loOK = gap(dmr, anyCode)
	s.lo = max(0, s.lo)
	if status == statusExact {
		s.hi, s.hiOK = s.lo, s.loOK
	} else {
		s.hi, s.hiOK = gap(aware, anyCode)
		if s.loOK && f1(s.lo) == f1(0) {
			s.loOK = false
		}
	}
	return s.text("")
}

func dbCell(c crossing) string {
	if !c.ok {
		return "-"
	}
	if c.below {
		return "< " + f1(c.ebn0)
	}
	return f1(c.ebn0)
}

func msCell(ns float64) string {
	ms := ns / 1e6
	switch {
	case ms >= 10:
		return grouped(int64(math.Round(ms)))
	case ms >= 1:
		return strconv.FormatFloat(math.Round(ms*10)/10, 'f', 1, 64)
	}
	return strconv.FormatFloat(math.Round(ms*100)/100, 'f', 2, 64)
}

type graph struct {
	key, title, rate string
}

func graphs() []graph {
	const fer = "Frame error rate"
	return []graph{
		{keyAMBE, "Voice frame", fer}, {keyRate12, "Data rate 1/2", fer}, {keyRate34, "Data rate 3/4", fer},
		{keyCSBK, labelCSBK, fer}, {keyELC, labelELC, fer}, {"rate1_bit", "Data rate 1 payload bits", "Bit error rate"},
	}
}

func errorRate(y []float64) []float64 {
	out := make([]float64, len(y))
	for i, v := range y {
		out[i] = 1 - v
	}
	return out
}

func renderGraphs(d data) map[string][]byte {
	out := map[string][]byte{}
	for _, m := range modes() {
		for _, g := range graphs() {
			out[m[0]+"/"+g.key+".svg"] = renderGraph(d, g, m[0])
		}
	}
	out["cpu.svg"] = cpuGraph(d)
	return out
}

func cpuGraph(d data) []byte {
	n := len(d.bench.Tiers)
	rows, typ, worst := make([]string, 0, n), make([]float64, 0, n), make([]float64, 0, n)
	for _, t := range d.bench.Tiers {
		rows = append(rows, shortName(t))
		typ, worst = append(typ, t.NsPerSecond/1e6), append(worst, t.WorstNs/1e6)
	}
	return barPlot("CPU per second of signal",
		plotAxis{min: 0.1, max: 1000, log: true, label: "CPU per second of signal (ms)"}, rows,
		[]barGroup{{name: "At C/N 6 dB", class: "q1", v: typ}, {name: "Worst case", class: "q2", v: worst}}, math.NaN())
}

func tierClass(t int) string { return "s" + strconv.Itoa(t+1) }

func renderGraph(d data, g graph, m string) []byte {
	var series []plotSeries
	if f, ok := d.floor.Payloads[g.key]; ok {
		series = append(series, plotSeries{name: "4FSK floor (any code)", x: f.Any.EbN0, y: errorRate(f.Any.recovery()), dash: "6 4", class: "r0"})
	}
	for _, t := range d.bench.Tiers {
		if t.Mode == m {
			x, y := tierCurve(t, g.key)
			series = append(series, plotSeries{name: "Tier " + strconv.Itoa(t.Tier), x: x, y: errorRate(y), class: tierClass(t.Tier), marks: true})
		}
	}
	return linePlot(g.title+", "+modeLabel(m)+": "+strings.ToLower(g.rate),
		plotAxis{min: -8, max: 14, step: 2, label: "Eb/N0 (dB)"}, plotAxis{min: 1e-4, max: 1, log: true, label: g.rate}, series)
}
