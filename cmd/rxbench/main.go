	endMarker   = "<!-- rxbench:end -->"
	specsBegin  = "<!-- rxbench:specs:begin -->"
	specsEnd    = "<!-- rxbench:specs:end -->"
	limitsBegin = "<!-- rxbench:limits:begin -->"
	limitsEnd   = "<!-- rxbench:limits:end -->"
	docName     = "docs/rx.md"
	graphDir    = "docs/rx"
	imgDir      = "rx/"
